/**
 * Черновик реплики обсуждения (ADMIN-PHASE-F, F9) — остаток D3.
 *
 * Набранный текст пропадал при закрытии вкладки: страж несохранённого ввода его не
 * ловит — он про модель, а не про панель обсуждения. Человек пишет длинный вопрос к
 * строке отчёта, отвлекается, закрывает вкладку — и пишет его заново.
 *
 * **Черновик живёт в браузере, а не на сервере.** У него ещё нет автора и времени: это
 * не реплика, а несказанные слова. Отправить их на сервер значило бы завести полуреплику
 * — сущность, которую пришлось бы показывать в ветке, чистить при удалении обсуждения и
 * объяснять в выгрузке организации.
 *
 * Отсюда и обещание, которое экран обязан держать буквально: **«остался в этом
 * браузере»**. Пообещать, что черновик найдётся на другом устройстве, нельзя — а молча
 * не найтись хуже, чем честно сказать заранее.
 *
 * **Черновики уходят вместе с выходом из системы.** Несказанные слова принадлежат тому,
 * кто их набрал; следующему человеку за этим же браузером их видеть незачем.
 *
 * Все обращения к хранилищу — в `try/catch`: в приватном окне и при запрещённом
 * хранилище доступ **бросает исключение**, и уронить из-за этого панель обсуждения
 * значило бы поменять работающую функцию на неработающую.
 */

/** Общий префикс. По нему же черновики стираются при выходе — списком, а не по одному. */
const PREFIX = "fe.draft.";

/** Ключ ветки: обсуждение о цене не должно подставлять черновик из обсуждения сроков. */
export function draftKey(kind: string, id: string, anchor = ""): string {
  return `${PREFIX}${kind}:${id}:${anchor}`;
}

export function readDraft(key: string): string {
  try {
    return localStorage.getItem(key) ?? "";
  } catch {
    // Приватное окно или запрещённое хранилище: черновика просто нет.
    return "";
  }
}

/**
 * Сохранить черновик. **Пустой текст стирает запись**, а не пишет пустую строку: иначе
 * «черновик остался» показывалось бы там, где человек всё стёр сам.
 */
export function writeDraft(key: string, text: string): void {
  try {
    if (text.trim()) localStorage.setItem(key, text);
    else localStorage.removeItem(key);
  } catch {
    // Не сохранилось — значит не сохранилось. Обещания «останется» панель не даёт,
    // пока черновик не прочитан обратно.
  }
}

export function clearDraft(key: string): void {
  writeDraft(key, "");
}

/**
 * Стереть все черновики этого браузера — при выходе из системы.
 *
 * Ключи собираются **до** удаления: удаление по ходу обхода сдвигает индексы, и половина
 * записей осталась бы — ровно та половина, которую труднее всего заметить.
 */
export function clearAllDrafts(): void {
  try {
    const keys: string[] = [];
    for (let i = 0; i < localStorage.length; i += 1) {
      const key = localStorage.key(i);
      if (key && key.startsWith(PREFIX)) keys.push(key);
    }
    keys.forEach((key) => localStorage.removeItem(key));
  } catch {
    // Нечего стирать либо хранилище недоступно.
  }
}

