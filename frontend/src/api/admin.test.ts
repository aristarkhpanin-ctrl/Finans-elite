import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { expect, it } from "vitest";

/**
 * Что служебный контур спрашивает у сервера (правило 6 плана B1 и его изменение в F4).
 *
 * Экранный тест на это не годится: он проверял бы, что мы не нарисовали то, чего нам не
 * присылали. Проверять надо **запросы** — они и есть граница. Сервер держит ту же
 * границу со своей стороны (`tests/test_admin_staff.py`, `tests/test_support_access.py`),
 * и оба обещания независимы: ослабнет одно — второе не промолчит.
 *
 * **Тест был слепым и это нашлось при F4.** Прежняя выборка адресов обрывалась на первой
 * же подстановке `${…}`, то есть у всех адресов с идентификатором в пути — а это ровно
 * те адреса, за которыми живёт содержимое. Она проходила бы и с запросом за моделью
 * клиента: адрес просто не доезжал до проверки. Теперь подстановка заменяется
 * заполнителем, и адрес проверяется целиком.
 */

const source = readFileSync(
  fileURLToPath(new URL("./admin.ts", import.meta.url)), "utf8");

/**
 * Адреса запросов — **целиком**, с подстановками, заменёнными на `{id}`.
 *
 * Без замены `/api/v1/admin/organizations/${orgId}/projects` превращался в
 * `/api/v1/admin/organizations/` — и хвост, ради которого тест и написан, пропадал.
 */
const urls = [...source.matchAll(/["'`](\/api\/v1\/[^"'`\n]*)/g)]
  .map((m) => m[1].replace(/\$\{[^}]*\}/g, "{id}"));

/** Адрес несёт содержимое модели клиента: проект, дело, группу, документ. */
const CONTENT = /\/projects|\/audit-subjects|\/audit\/subjects|\/audit\/groups|business-plan|report\.docx/;

/**
 * Запросы за содержимым — **перечень, и он закрыт** (F4).
 *
 * Правило 6 не отменено: у него появился ключ, и ключ у клиента. Эти четыре запроса
 * работают только при живом гранте организации, и каждое обращение попадает в её
 * журнал. Пятый запрос за содержимым обязан пройти через этот список, а не появиться
 * между экранами наблюдения.
 */
const BEHIND_A_GRANT = [
  "/api/v1/admin/organizations/{id}/projects",
  "/api/v1/admin/organizations/{id}/projects/{id}",
  "/api/v1/admin/organizations/{id}/audit-subjects",
  "/api/v1/admin/organizations/{id}/audit-subjects/{id}",
];

it("ходит только в служебный контур", () => {
  expect(urls.length).toBeGreaterThan(0);
  for (const url of urls) expect(url.startsWith("/api/v1/admin")).toBe(true);
});

it("выборка адресов видит их целиком, а не до первой подстановки", () => {
  // Сторож самого теста. Обрезанная выборка пропустила бы любой запрос за моделью —
  // и сделала бы это молча, оставив зелёный тест как доказательство границы.
  expect(urls).toContain("/api/v1/admin/organizations/{id}/audit-log");
});

it("за содержимым моделей ходит только перечисленное — и только по гранту", () => {
  // Метаданные — да (организации, пользователи, журнал, сотрудники), содержимое — по
  // гранту клиента и нигде больше. Запрос за моделью, появившийся мимо перечня, означал
  // бы, что владелец SaaS читает финансовые модели своих клиентов без их ведома.
  const content = urls.filter((u) => CONTENT.test(u));
  expect([...new Set(content)].sort()).toEqual([...BEHIND_A_GRANT].sort());
});
