"""Каталог строк ввода фактической отчётности (аналитическая форма, РСБУ-агрегаты).

Финанс-Аудит (продукт №2). Пользователь вводит эти агрегированные статьи по периодам;
итог актива = Σ активов, итог пассива = Σ (капитал + обязательства); их равенство —
инвариант «актив = пассив». Расшифровки (Приложение А спецификации) — v2.
"""
from __future__ import annotations

# Актив (сумма = суммарный актив).
BALANCE_ASSET_LINES: list[tuple[str, str]] = [
    ("A_FIXED", "Внеоборотные активы"),
    ("A_INVENTORY", "Запасы"),
    ("A_RECEIVABLE", "Дебиторская задолженность"),
    ("A_CASH", "Денежные средства и эквиваленты"),
]

# Пассив (капитал + обязательства; сумма = суммарный пассив).
BALANCE_EQLIAB_LINES: list[tuple[str, str]] = [
    ("P_EQUITY", "Капитал и резервы"),
    ("P_LONG", "Долгосрочные обязательства"),
    ("P_SHORT", "Краткосрочные обязательства"),
]

# Отчёт о финансовых результатах (вводимые статьи; подытоги — производные, считаются движком).
INCOME_LINES: list[tuple[str, str]] = [
    ("I_REVENUE", "Выручка"),
    ("I_COGS", "Себестоимость продаж"),
    ("I_OPEX", "Коммерческие и управленческие расходы"),
    ("I_INTEREST", "Проценты к уплате"),
    ("I_OTHER", "Прочие доходы/расходы (сальдо)"),
    ("I_TAX", "Налог на прибыль"),
]

# Справочные (memo) строки: **не входят в итоги баланса** — расшифровка для диагностики.
# Нераспределённая прибыль нужна моделям Альтмана (фактор «накопленная прибыль / активы»);
# в агрегате «Капитал и резервы» она уже учтена, поэтому в сумму пассива не добавляется.
# Рыночная капитализация — не учётная величина: она есть только у публичной компании и
# нужна классической модели Альтмана (фактор «рыночная стоимость капитала / обязательства»).
MEMO_LINES: list[tuple[str, str]] = [
    ("M_RETAINED", "в т.ч. нераспределённая прибыль (для диагностики)"),
    ("M_MARKET_CAP", "рыночная капитализация (только для публичных компаний)"),
]

ASSET_CODES = [c for c, _ in BALANCE_ASSET_LINES]
EQLIAB_CODES = [c for c, _ in BALANCE_EQLIAB_LINES]
INCOME_CODES = [c for c, _ in INCOME_LINES]
MEMO_CODES = [c for c, _ in MEMO_LINES]
BALANCE_CODES = ASSET_CODES + EQLIAB_CODES

# Справочные строки, которые **складываются** при консолидации группы. Нераспределённая
# прибыль аддитивна (учётная величина каждого участника). Рыночная капитализация — нет:
# капитализация материнской компании уже включает стоимость дочерних, и сумма по группе
# была бы двойным счётом. Поэтому в свод она не переносится, а классическая модель
# Альтмана для группы просто не считается — вместо правдоподобного, но ложного числа.
MEMO_SUM_CODES = ["M_RETAINED"]

LABELS: dict[str, str] = dict(
    BALANCE_ASSET_LINES + BALANCE_EQLIAB_LINES + INCOME_LINES + MEMO_LINES
)
