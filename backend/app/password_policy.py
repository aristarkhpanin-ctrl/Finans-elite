"""Требования к паролю: что проверяем и чего **не** требуем (C2).

До этой фазы правило было одно — «не короче 8 символов». Оно пропускало `12345678`,
`qwertyui` и собственный адрес пользователя, то есть ровно то, чем ломают учётные записи
в первую очередь.

**Состав символов не требуется — и это решение, а не упущение.** Правило «заглавная,
цифра и знак» даёт `Parol123!`: пользователь выполняет букву требования, энтропии не
прибавляется, зато пароль становится невозможно запомнить и уезжает на бумажку под
клавиатуру. NIST отказался от требований к составу в SP 800-63B по этой самой причине;
вместо них — длина и **проверка по спискам**, что здесь и сделано.

Правила — чистые функции без базы и сети, поэтому проверяются обычными тестами. Проверка
по утёкшим паролям живёт отдельно (:mod:`app.pwned`): она ходит в сеть и может быть
недоступна, а эти правила работают всегда.

Каждый отказ **называет, что не так и что делать**. «Пароль не подходит» отправляет
человека перебирать варианты вслепую — и он придёт к чему-нибудь вроде `Parol1234!`.
"""
from __future__ import annotations

import re
import unicodedata

#: Минимальная длина. Одно правило на все три двери, где пароль задаётся: регистрация,
#: активация ссылки и смена. Разные пороги в разных дверях — не строгость, а её иллюзия.
MIN_LENGTH = 8

#: Самые частые пароли — латиница и кириллица. Список **короткий и честный**: он не
#: заменяет проверку по утечкам (:mod:`app.pwned`), а ловит то, что вводят, не задумываясь.
#: Полный список из миллионов строк в коде держать нельзя, и притворяться, что он здесь
#: есть, — тоже.
COMMON = frozenset({
    "password", "passw0rd", "qwerty", "qwerty123", "qwertyui", "123456", "1234567",
    "12345678", "123456789", "1234567890", "111111", "000000", "iloveyou", "admin",
    "administrator", "welcome", "letmein", "monkey", "dragon", "football", "master",
    "sunshine", "princess", "superman", "trustno1", "zaq12wsx", "1q2w3e4r", "1qaz2wsx",
    "пароль", "парольпароль", "йцукен", "йцукенгш", "любовь", "россия", "москва",
    "привет", "фывапролд", "123qwe", "qazwsx", "abc123", "changeme", "secret",
})

#: Клавиатурные ряды: по ним «придумывают» пароль, ведя пальцем по клавиатуре.
_KEYBOARD = ("qwertyuiop", "asdfghjkl", "zxcvbnm", "йцукенгшщзхъ", "фывапролджэ",
             "ячсмитьбю", "1234567890")

#: Сколько подряд идущих символов ряда считать «последовательностью». Три — слишком
#: строго: `abc` внутри осмысленного слова встречается сплошь и рядом.
_RUN = 4


def _fold(value: str) -> str:
    """К нижнему регистру и без диакритики — чтобы `PaSsWoRd` не обошёл список."""
    return unicodedata.normalize("NFKD", value).casefold()


def _has_run(password: str) -> bool:
    folded = _fold(password)
    for row in _KEYBOARD:
        reverse = row[::-1]
        for start in range(len(row) - _RUN + 1):
            if row[start:start + _RUN] in folded or reverse[start:start + _RUN] in folded:
                return True
    return False


def _looks_like_email_part(password: str, email: str) -> bool:
    """Пароль повторяет имя из адреса? `ivan@example.ru` → `ivan2026` не годится.

    Берём часть до `@` и, если она достаточно длинная, ищем её в пароле: адрес человека
    знает всякий, кому он писал, — это не секрет и секретом быть не может.
    """
    local = _fold(email).split("@")[0]
    local = re.sub(r"[^a-zа-я0-9]", "", local)
    return len(local) >= 4 and local in _fold(password)


def check_password(password: str, *, email: str = "") -> str:
    """Пустая строка — пароль годится; иначе текст отказа для пользователя.

    Возвращается **текст**, а не код: сообщение пойдёт человеку, и переводить код в
    слова пришлось бы на каждом экране заново — а значит, однажды по-разному.
    """
    if len(password) < MIN_LENGTH:
        return f"Пароль должен быть не короче {MIN_LENGTH} символов"
    if _fold(password) in COMMON:
        return ("Этот пароль слишком известен — он есть в любом списке для подбора. "
                "Придумайте другой")
    if len(set(password)) == 1:
        return "Пароль из одного повторяющегося символа подбирается мгновенно"
    if _has_run(password):
        return ("В пароле есть подряд идущие символы клавиатуры (например «qwer» или "
                "«1234») — их подбирают в первую очередь")
    if email and _looks_like_email_part(password, email):
        return ("Пароль повторяет ваш адрес — его знает каждый, кому вы писали. "
                "Придумайте другой")
    return ""


def policy_rules(*, leak_check: bool) -> list[str]:
    """Что именно проверяется — для показа на экране.

    Список собирается **из тех же правил**, что и проверяют: экран, перечисляющий
    требования отдельным текстом, однажды разойдётся с сервером, и человек будет читать
    одно, а получать другое. Проверка по утечкам названа только когда она включена: иначе
    платформа обещала бы то, чего не делает.
    """
    rules = [
        f"Не короче {MIN_LENGTH} символов.",
        "Не из списка самых частых паролей и не набор подряд идущих клавиш.",
        "Не повторяет ваш адрес электронной почты.",
        "Заглавные буквы и знаки препинания **не требуются**: они дают «Parol123!», "
        "который не надёжнее и который невозможно запомнить.",
    ]
    if leak_check:
        rules.append("Проверяется по базе утёкших паролей — сам пароль при этом "
                     "никуда не отправляется, только первые пять знаков его отпечатка.")
    return rules
