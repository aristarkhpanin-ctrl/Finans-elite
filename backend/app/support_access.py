"""Доступ поддержки к моделям клиента — по его собственному гранту (ADMIN-PHASE-F, F4).

**Это единственное изменение правила 6 во всей фазе.** До сих пор оператор видел клиента
строго снаружи: тарифы, объёмы, состав, — и ни одного числа из проекта или дела. Правило
стояло не зря: владелец SaaS, читающий финансовые модели своих клиентов, — ровно то,
чего клиент и опасается.

Оно и не отменяется. Меняется другое: у клиента появляется возможность **позвать** нас
внутрь. «У меня не считается проект, посмотрите» — обычная просьба, и до сих пор ответом
было «пришлите выгрузку»: клиент пересылал модель почтой, то есть тем самым каналом,
который платформа для этого и заменяет.

Форма была предложена ещё в списке «осознанно не делаем» и принимается **целиком**;
изменение без всех трёх ограничений не принимается вовсе:

1. **Выдаёт клиент, а не платформа.** Оператор не может ни выдать себе грант, ни продлить
   чужой. Отказ без гранта прямо говорит, где его взять, — иначе поддержка начнёт просить
   выгрузку почтой, и всё вернётся к тому, с чего начали.
2. **Грант ограничен по времени** — не более :data:`MAX_GRANT_HOURS`. «Бессрочный грант»
   это не грант, а тихая отмена правила: выданный однажды, он работал бы годами, и клиент
   о нём забыл бы на второй день.
3. **Каждое чтение пишется в журнал клиента.** Названное исключение из «журнал не пишет
   чтение» — то же, что у визита в карточку: приход постороннего в свои числа клиент
   обязан видеть **построчно**, а не одной записью «доступ выдан».

И четвёртое, которое из формы следует: **грант даёт чтение и только чтение**. Ни правки,
ни удаления, ни расчёта от чужого имени — поддержка смотрит и рассказывает, а меняет
клиент. Перечень власти оператора (F5) от гранта не вырос ни на один маршрут, и это
перечень-тест.

Функции здесь **чистые**: о хранилище и о часах они не знают, время приходит параметром.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from typing import Iterable, Protocol

#: Предел срока гранта. Семьдесят два часа — это «до конца рабочей недели, если позвали
#: в среду»: дольше разбор обращения не живёт, а грант, переживший разбор, становится
#: постоянным доступом, о котором никто не помнит.
MAX_GRANT_HOURS = 72

#: Отказ без гранта. Называет **не нехватку прав**, а недостающее действие клиента: иначе
#: оператор пойдёт искать у себя кнопку, которой у него нет и не будет.
NO_GRANT = (
    "Клиент не открывал доступ к своим моделям. Содержимое проектов и дел платформе не "
    "видно: доступ выдаёт сама организация — «Организация → Доступ поддержки», на срок "
    "не более {hours} ч и с указанием причины."
)

#: Отказ по истёкшему гранту говорит **что именно истекло**: «нет доступа» после того,
#: как клиент его только что выдал, читается как поломка.
GRANT_EXPIRED = (
    "Доступ, открытый клиентом, истёк {when}. Продлить его может только сама организация "
    "— платформа свой доступ не продлевает."
)

GRANT_REVOKED = (
    "Клиент закрыл доступ к своим моделям {when}. Открыть заново может только он сам."
)

#: Оговорка клиенту. Грант **на организацию, а не на проект**: сузить его до одной модели
#: значило бы обещать больше, чем платформа делает, — и это сказано там, где выдают.
SCOPE_NOTE = (
    "Доступ открывается ко **всем** проектам и делам организации, а не к одному: "
    "выбрать отдельную модель платформа не умеет, и делать вид, что умеет, хуже. "
    "Каждое обращение сотрудника платформы к вашим числам попадает в журнал "
    "организации отдельной строкой — там видно, кто и что смотрел."
)

READ_ONLY_NOTE = (
    "Сотрудник платформы может только смотреть: правка, удаление и расчёт от вашего "
    "имени грантом не открываются."
)


class Grant(Protocol):
    """То немногое, что правилам нужно знать о строке гранта."""

    expires_at: datetime
    revoked_at: datetime | None


@dataclass(frozen=True)
class Refusal:
    """Почему смотреть нельзя. Причина **всегда** названа — «нет доступа» без причины
    отправляет оператора искать ошибку у себя."""

    reason: str


def clamp_hours(hours: int) -> int:
    """Срок гранта в допустимых пределах.

    Обрезка молчаливой не бывает: маршрут сверяет возвращённое с запрошенным и говорит
    клиенту, что срок сокращён. Обрезать и промолчать значило бы показать «до пятницы»
    там, где доступ кончится в среду.
    """
    return max(1, min(int(hours), MAX_GRANT_HOURS))


def expiry_of(hours: int, now: datetime) -> datetime:
    return now + timedelta(hours=clamp_hours(hours))


def _aware(value: datetime) -> datetime:
    """SQLite отдаёт время без зоны; сравнивать наивное с осведомлённым — исключение.

    Наивное значение читается как UTC: именно в нём всё и пишется (``_now``).
    """
    return value if value.tzinfo is not None else value.replace(tzinfo=timezone.utc)


def is_live(grant: Grant, now: datetime) -> bool:
    return grant.revoked_at is None and _aware(grant.expires_at) > now


def live_grant(grants: Iterable[Grant], now: datetime) -> Grant | None:
    """Действующий грант — или ``None``.

    Живой грант в организации **один**: выдача закрывает предыдущий. Два действующих
    гранта с разными сроками и причинами означали бы, что «до какого часа открыто»
    зависит от того, какой из них посмотреть.
    """
    for grant in grants:
        if is_live(grant, now):
            return grant
    return None


def refusal_for(grants: Iterable[Grant], now: datetime, *,
                fmt_when=str) -> Refusal | None:
    """``None``, если смотреть можно, иначе — отказ с причиной.

    Причины три и они разные: доступ **не открывали**, доступ **истёк**, доступ
    **закрыли**. Свести их к одной («нет доступа») значило бы отвечать «может быть, вы
    ошиблись» там, где клиент только что нажал «закрыть».
    """
    rows = list(grants)
    if live_grant(rows, now) is not None:
        return None
    if not rows:
        return Refusal(NO_GRANT.format(hours=MAX_GRANT_HOURS))
    # Последний по времени — тот, о котором клиент помнит; по нему и объясняем.
    last = rows[0]
    if last.revoked_at is not None:
        return Refusal(GRANT_REVOKED.format(when=fmt_when(_aware(last.revoked_at))))
    return Refusal(GRANT_EXPIRED.format(when=fmt_when(_aware(last.expires_at))))
