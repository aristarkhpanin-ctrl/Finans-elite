"""Обсуждение рядом с числами: разбор упоминаний и правила комментария (D3).

Чистые функции: ни базы, ни почты — их зовёт роутер. Здесь живут решения, которые иначе
расползлись бы по маршрутам и разошлись бы между продуктами.

**Упоминание не даёт прав.** `@ivan@company.ru` зовёт человека посмотреть, а не открывает
ему проект: доступ решает роль в организации. Упомянуть можно **только участника своей
организации** — упоминание чужого адреса либо утечка (адрес уходит в письмо и в текст),
либо ложь (человек не придёт, а автор будет ждать). Нераспознанное упоминание **названо**,
а не проглочено: «позвал и никто не пришёл» — худший вид тишины.

**Текст комментария не правится.** Отредактированная реплика, на которую уже ответили,
переписывает историю: спор становится непонятным, а согласие — приписанным. Удалить свою
реплику можно, но на её месте остаётся «надгробие»: пропавшая без следа строка читается
как не сказанная никогда.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

#: Адрес после `@`. Намеренно строгий: `@ivan` без домена — это не адрес, и угадывать,
#: кого имели в виду, платформа не станет (в организации бывают тёзки).
_MENTION = re.compile(r"@([A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,})")

#: Предел длины реплики — как у поля в базе. Обрезать молча нельзя: человек не увидит,
#: что половина сказанного не сохранилась.
MAX_BODY = 4000

#: Кого зовём одной репликой. Двадцать адресов — уже рассылка, а не разговор.
MAX_MENTIONS = 20


@dataclass
class Mentions:
    """Разбор упоминаний: кого позвали и кого позвать не вышло."""

    #: Адреса участников организации — им уйдёт письмо (если почта настроена).
    known: list[str] = field(default_factory=list)
    #: Упомянутые, которых в организации нет. Названы автору, а не проглочены.
    unknown: list[str] = field(default_factory=list)

    @property
    def too_many(self) -> bool:
        return len(self.known) + len(self.unknown) > MAX_MENTIONS


def parse_mentions(body: str, members: dict[str, str]) -> Mentions:
    """Найти упоминания в тексте и разделить их на «свои» и «никого».

    ``members`` — адреса участников организации в нижнем регистре → как они записаны.
    Сравнение по нижнему регистру: почта регистронезависима в той части, которая нас
    касается, и `@Ivan@Company.ru` обязан найти того же человека.
    """
    seen: list[str] = []
    for raw in _MENTION.findall(body or ""):
        low = raw.lower()
        if low not in seen:
            seen.append(low)
    known = [members[a] for a in seen if a in members]
    unknown = [a for a in seen if a not in members]
    return Mentions(known=known, unknown=unknown)


def check_body(body: str) -> str:
    """Проверить реплику. Пустая строка — всё в порядке; иначе текст отказа."""
    text = (body or "").strip()
    if not text:
        return "Пустой комментарий: напишите, что обсуждаем."
    if len(text) > MAX_BODY:
        return (f"Комментарий длиннее {MAX_BODY} символов — его пришлось бы обрезать. "
                "Разбейте на несколько реплик.")
    return ""


#: Как называется удалённая реплика. Текст один на все выходы — и он **не врёт про
#: автора**: администратор организации тоже может убрать чужую реплику, и «удалена
#: автором» под таким удалением приписало бы человеку чужое решение.
DELETED_BY_AUTHOR = "Реплика удалена автором."
DELETED_BY_ADMIN = "Реплика удалена администратором организации."


def visible_body(comment) -> str:
    """Текст реплики для показа: удалённая говорит о себе, а не исчезает."""
    if comment.deleted_at is None:
        return comment.body
    own = comment.deleted_by and comment.deleted_by == comment.author_email
    return DELETED_BY_AUTHOR if own else DELETED_BY_ADMIN
