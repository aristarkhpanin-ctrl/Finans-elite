"""Обсуждение рядом с числами: разбор упоминаний и правила комментария (D3).

Чистые функции: ни базы, ни почты — их зовёт роутер. Здесь живут решения, которые иначе
расползлись бы по маршрутам и разошлись бы между продуктами.

**Упоминание не даёт прав.** `@ivan@company.ru` зовёт человека посмотреть, а не открывает
ему проект: доступ решает роль в организации. Упомянуть можно **только участника своей
организации** — упоминание чужого адреса либо утечка (адрес уходит в письмо и в текст),
либо ложь (человек не придёт, а автор будет ждать). Нераспознанное упоминание **названо**,
а не проглочено: «позвал и никто не пришёл» — худший вид тишины.

**Текст комментария не правится.** Отредактированная реплика, на которую уже ответили,
переписывает историю: спор становится непонятным, а согласие — приписанным. Удалить свою
реплику можно, но на её месте остаётся «надгробие»: пропавшая без следа строка читается
как не сказанная никогда.
"""
from __future__ import annotations

import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone

#: Адрес после `@`. Намеренно строгий в одном: `@ivan` без домена — это не адрес, и
#: угадывать, кого имели в виду, платформа не станет (в организации бывают тёзки).
#:
#: Но **буквы любые**, включая кириллицу. Первая версия знала только латиницу, и
#: `@иван@компания.рф` не считался упоминанием вовсе: ни письма, ни даже оговорки «в
#: организации нет такого» — автор звал, и никто не приходил, ровно то молчание, против
#: которого этот разбор и написан. Продукт русский, адреса участников платформа
#: принимает любые — значит и звать умеет любых.
_MENTION = re.compile(r"@([^\s@,;:!?()\[\]<>«»\"]+@[^\s@,;:!?()\[\]<>«»\".]+\.\w{2,})",
                      re.UNICODE)

#: Предел длины реплики — как у поля в базе. Обрезать молча нельзя: человек не увидит,
#: что половина сказанного не сохранилась.
MAX_BODY = 4000

#: Кого зовём одной репликой. Двадцать адресов — уже рассылка, а не разговор.
MAX_MENTIONS = 20


@dataclass
class Mentions:
    """Разбор упоминаний: кого позвали и кого позвать не вышло."""

    #: Адреса участников организации — им уйдёт письмо (если почта настроена).
    known: list[str] = field(default_factory=list)
    #: Упомянутые, которых в организации нет. Названы автору, а не проглочены.
    unknown: list[str] = field(default_factory=list)

    @property
    def too_many(self) -> bool:
        return len(self.known) + len(self.unknown) > MAX_MENTIONS


def parse_mentions(body: str, members: dict[str, str]) -> Mentions:
    """Найти упоминания в тексте и разделить их на «свои» и «никого».

    ``members`` — адреса участников организации в нижнем регистре → как они записаны.
    Сравнение по нижнему регистру: почта регистронезависима в той части, которая нас
    касается, и `@Ivan@Company.ru` обязан найти того же человека.
    """
    seen: list[str] = []
    for raw in _MENTION.findall(body or ""):
        low = raw.lower()
        if low not in seen:
            seen.append(low)
    known = [members[a] for a in seen if a in members]
    unknown = [a for a in seen if a not in members]
    return Mentions(known=known, unknown=unknown)


def check_body(body: str) -> str:
    """Проверить реплику. Пустая строка — всё в порядке; иначе текст отказа."""
    text = (body or "").strip()
    if not text:
        return "Пустой комментарий: напишите, что обсуждаем."
    if len(text) > MAX_BODY:
        return (f"Комментарий длиннее {MAX_BODY} символов — его пришлось бы обрезать. "
                "Разбейте на несколько реплик.")
    return ""


#: Как называется удалённая реплика. Текст один на все выходы — и он **не врёт про
#: автора**: администратор организации тоже может убрать чужую реплику, и «удалена
#: автором» под таким удалением приписало бы человеку чужое решение.
DELETED_BY_AUTHOR = "Реплика удалена автором."
DELETED_BY_ADMIN = "Реплика удалена администратором организации."


def visible_body(comment) -> str:
    """Текст реплики для показа: удалённая говорит о себе, а не исчезает."""
    if comment.deleted_at is None:
        return comment.body
    own = comment.deleted_by and comment.deleted_by == comment.author_email
    return DELETED_BY_AUTHOR if own else DELETED_BY_ADMIN


# --- Кому уходит письмо о новой реплике (OPEN-DECISIONS §5) ---
#
# Дайджест «что произошло за день» перестают читать на второй неделе, и он требует
# решений о времени, часовом поясе и составе. Настоящий вопрос человека другой —
# **«мне ответили?»**, и отвечает на него подписка на ветку.

#: Пауза между письмами об одной ветке одному человеку. Три реплики подряд не должны
#: давать три письма: разговор идёт очередями, и письмо на каждую строку — это рассылка.
#:
#: Час — не «настройка на будущее», а решение: матрица «как часто и о чём» заполняется
#: один раз и больше не открывается, а человек, которому письма мешают, ищет не ползунок,
#: а выключатель. Выключателей два — отписка от ветки и общий в профиле.
NOTIFY_PAUSE = timedelta(hours=1)


@dataclass(frozen=True)
class ThreadState:
    """Что платформа знает о письмах этому человеку об этой ветке."""

    #: Человек отписался от ветки.
    muted: bool = False
    #: Когда ему в последний раз писали об этой ветке (``None`` — ни разу).
    last_notified: datetime | None = None


def thread_participants(rows: Sequence) -> list[str]:
    """Кто в разговоре: написал реплику **или был в ней упомянут**.

    Участие выводится из самих реплик, а не хранится списком: отдельный список подписчиков
    — вторая правда, и она отстала бы от разговора при первой же реплике, написанной мимо
    экрана (импортом, другим клиентом, чем угодно).

    Порядок — по первому появлению; регистр адреса — как он записан в первой встрече.
    Удалённые реплики в счёт **идут**: автор в разговоре был, и то, что он потом убрал
    свои слова, не делает его посторонним (текст стёрт, но ``author_email`` — «надгробие»
    — остался; упоминания у удалённой реплики стёрты вместе с текстом).
    """
    seen: dict[str, str] = {}
    for row in rows:
        for email in [row.author_email, *row.mentions.split(",")]:
            address = (email or "").strip()
            if address and address.lower() not in seen:
                seen[address.lower()] = address
    return list(seen.values())


def reply_targets(participants: Iterable[str], *, author_email: str,
                  mentioned: Iterable[str], members: Iterable[str],
                  state: dict[str, ThreadState], now: datetime) -> list[str]:
    """Кому уйдёт письмо «в обсуждении новая реплика».

    Отсев — по пяти причинам, и каждая своя:

    * **автор реплики** — письмо самому себе о собственных словах это шум, из-за которого
      перестают читать остальные (то же правило, что у упоминания самого себя);
    * **упомянутые в этой самой реплике** — им уже уходит письмо об упоминании, и второе
      письмо об одной строке это ровно та рассылка, против которой пауза и написана;
    * **не участники организации** — участник ветки мог уйти из компании, а разговор о её
      делах остался; письмо о нём наружу не уезжает;
    * **отписавшиеся** от ветки;
    * **те, кому уже писали** об этой ветке меньше паузы назад.

    ``state`` — по адресу в нижнем регистре. Адреса, которого в нём нет, ещё не писали ни
    разу: ``None`` здесь значит «не писали», а не «писали давно».
    """
    skip = {(author_email or "").lower()}
    skip |= {m.lower() for m in mentioned}
    allowed = {m.lower() for m in members}
    out: list[str] = []
    for email in participants:
        low = email.lower()
        if low in skip or low not in allowed:
            continue
        seen = state.get(low, ThreadState())
        if seen.muted:
            continue
        if seen.last_notified is not None and _utc(now) - _utc(seen.last_notified) \
                < NOTIFY_PAUSE:
            continue
        out.append(email)
    return out


def _utc(value: datetime) -> datetime:
    """Наивное время — это время SQLite: он отдаёт его без пояса. Сравнить его с
    осведомлённым нельзя, и падать посреди отправленной реплики из-за этого мы не станем."""
    return value if value.tzinfo is not None else value.replace(tzinfo=timezone.utc)
