"""Почта платформы: письма и способ их отправить (ADMIN-DECOMPOSITION.md, D1).

До этой фазы у продукта не было ни одного исходящего письма, и всё держалось на «ссылку
передайте лично». Это не мелочь: приглашённый не мог войти, пока пригласивший не дошёл до
него ногами, а забытый пароль владельца организации не восстанавливался **никак**.

**Пока почта не настроена, платформа не делает вид, что письма уходят.** Это правило
дома в его самом буквальном виде: строчка «приглашение отправлено», за которой ничего не
происходило, однажды уже стоила приглашённым нескольких дней ожидания письма, которого
не было. Поэтому:

* отправка выключена по умолчанию (``MAIL_BACKEND=off``) — включает её тот, кто задал
  адрес сервера и проверил, что письма доходят;
* :func:`mail_enabled` спрашивают **все**, кто собирается сказать человеку «письмо ушло»,
  — экран входа, приглашение участника, выдача ссылки;
* :func:`send` **не бросает исключений и не врёт**: неудача возвращается вызывающему
  словами, и он обязан её показать. Письмо, потерянное молча, хуже неотправленного.

**Ручная ссылка не исчезает.** Почта — добавление к «передайте лично», а не замена: при
неудачной отправке (а её причин не счесть — от опечатки в адресе до чужого спам-фильтра)
администратор по-прежнему видит ссылку и передаёт её сам.

**Ответы на письма никто не читает.** Ящика для входящей почты у платформы нет, и каждое
письмо говорит об этом прямо: тишина в ответ на «а что это было?» выглядит как
пренебрежение, а на деле письмо просто некуда прислать.
"""
from __future__ import annotations

import logging
import os
import smtplib
from dataclasses import dataclass
from email.headerregistry import Address
from email.message import EmailMessage

log = logging.getLogger("finans")

#: Как отправляем: ``off`` (по умолчанию — не отправляем вовсе), ``smtp`` (настоящий
#: сервер), ``memory`` (складываем в список — тесты и разработка).
_BACKENDS = ("off", "smtp", "memory")

def public_url() -> str:
    """Куда ведут ссылки в письмах. Письмо уходит наружу, и относительный путь в нём
    бесполезен: адрес приложения знает только тот, кто его развернул.

    Читается на каждом вызове, а не при импорте — как и всё остальное окружение здесь:
    модуль импортируется один раз за процесс, а переменные меняют и тесты, и
    эксплуатация.
    """
    return os.getenv("PUBLIC_URL", "").rstrip("/")


def backend() -> str:
    """Читается на каждом вызове, а не при импорте: окружение меняют и тесты, и
    эксплуатация, а модуль импортируется один раз за процесс."""
    value = os.getenv("MAIL_BACKEND", "off").strip().lower() or "off"
    return value if value in _BACKENDS else "off"


def mail_enabled() -> bool:
    """Отправляем ли мы письма вообще.

    Спрашивают все, кто собирается пообещать человеку письмо. Отдельного «мягкого»
    состояния («вроде настроена, но не уверены») нет намеренно: обещание либо есть, либо
    его не дают.
    """
    return backend() != "off"


def _timeout() -> float:
    """Секунды на разговор с сервером. Короткий: отправка стоит посреди чужого действия."""
    return float(os.getenv("SMTP_TIMEOUT", "10"))


def _smtp_settings() -> tuple[str, int, str, str, str]:
    host = os.getenv("SMTP_HOST", "").strip()
    if not host:
        # Fail-fast с названной причиной — как с ``JWT_SECRET``: «включил отправку, но
        # не сказал куда» это не рабочее состояние, а тихо не уходящие письма.
        raise RuntimeError("MAIL_BACKEND=smtp, но SMTP_HOST не задан: "
                           "укажите адрес почтового сервера или выключите отправку")
    mode = os.getenv("SMTP_TLS", "starttls").strip().lower()
    default_port = "465" if mode == "ssl" else "587"
    return (host, int(os.getenv("SMTP_PORT", default_port)),
            os.getenv("SMTP_USER", ""), os.getenv("SMTP_PASSWORD", ""), mode)


@dataclass(frozen=True)
class Letter:
    """Готовое письмо: тема и текст. Без HTML — намеренно.

    Письмо платформы состоит из одной ссылки и двух абзацев объяснения; вёрстка добавила
    бы к нему только повод для спам-фильтра и вторую версию текста, которая разойдётся с
    первой.
    """

    subject: str
    text: str
    #: **Информационное** ли письмо: рассказ о том, что произошло (вход с нового
    #: устройства, упоминание в обсуждении), а не способ войти.
    #:
    #: Признак живёт здесь, рядом с текстом, а не в вызове отправки: следующее
    #: информационное письмо допишут в этот файл — и тут же увидят поле, — а флаг в
    #: чужом вызове забудут, и чужая активность поедет в чужой ящик.
    #:
    #: Информационные письма **не уходят на неподтверждённый адрес**: опечатка в нём
    #: превращает утечку в ежедневную. Дверные (приглашение, ссылка администратора,
    #: восстановление пароля) уходят всегда — они единственный способ войти, и запереть
    #: их значило бы запереть человека.
    informational: bool = False


@dataclass(frozen=True)
class Sent:
    """Чем кончилась отправка. ``ok=False`` — вызывающий обязан сказать это человеку."""

    ok: bool
    #: Причина словами (пустая при успехе) — она уходит на экран, а не только в лог.
    error: str = ""
    #: Пытались ли вообще: ``False`` при выключенной почте. «Не отправляли» и
    #: «отправляли, не вышло» — разные ответы, и путать их нельзя.
    attempted: bool = True


#: Письма, отправленные бэкендом ``memory`` — для тестов и разработки.
_outbox: list[tuple[str, Letter]] = []


def outbox() -> list[tuple[str, Letter]]:
    """Что «ушло» в режиме ``memory``: пары (адрес, письмо)."""
    return list(_outbox)


def clear_outbox() -> None:
    _outbox.clear()


def send(to: str, letter: Letter) -> Sent:
    """Отправить письмо. **Не бросает исключений** — неудача возвращается словами.

    Отправка стоит посреди чужого действия: приглашения участника, входа, сброса пароля.
    Уронить это действие из-за недоступного почтового сервера значило бы поставить работу
    платформы в зависимость от чужой — тот же довод, что у проверки паролей по утечкам.
    Поэтому неудача не исключение, а **часть ответа**, и вызывающий обязан её показать.
    """
    kind = backend()
    if kind == "off":
        return Sent(ok=False, attempted=False,
                    error="почта не настроена: письма платформа не отправляет")
    if not to or "@" not in to:
        return Sent(ok=False, error=f"адрес «{to}» не похож на почтовый")
    if kind == "memory":
        _outbox.append((to, letter))
        return Sent(ok=True)
    try:
        _send_smtp(to, letter)
    except (OSError, smtplib.SMTPException) as exc:            # noqa: BLE001 — см. выше
        log.warning("письмо не отправлено на %s: %s", to, exc)
        return Sent(ok=False, error=f"почтовый сервер не принял письмо: {exc}")
    return Sent(ok=True)


def _send_smtp(to: str, letter: Letter) -> None:
    host, port, user, password, mode = _smtp_settings()
    message = EmailMessage()
    message["Subject"] = letter.subject
    local, _, domain = os.getenv("MAIL_FROM", "no-reply@finans-elite.ru").partition("@")
    message["From"] = Address(os.getenv("MAIL_FROM_NAME", "Финанс-Элит"), local, domain)
    message["To"] = to
    message.set_content(letter.text)
    if mode == "ssl":
        with smtplib.SMTP_SSL(host, port, timeout=_timeout()) as smtp:
            _deliver(smtp, user, password, message)
        return
    with smtplib.SMTP(host, port, timeout=_timeout()) as smtp:
        if mode == "starttls":
            smtp.starttls()
        _deliver(smtp, user, password, message)


def _deliver(smtp: smtplib.SMTP, user: str, password: str, message: EmailMessage) -> None:
    if user:
        smtp.login(user, password)
    smtp.send_message(message)


# --- Тексты писем ---
#
# Все письма устроены одинаково: что произошло, что сделать, что делать, если это были
# не вы, и подпись с оговоркой про ответы. Пароля и кода второго фактора в письмах нет
# **никогда** — только одноразовые ссылки, которые гаснут после использования.

_SIGNATURE = ("\n\n—\nЭто письмо отправила платформа «Финанс-Элит».\n"
              "Отвечать на него бесполезно: ящик входящие письма не принимает.")


def activation_url(token: str) -> str:
    """Ссылка активации для письма. Без ``PUBLIC_URL`` — путь: пусть лучше человек
    подставит адрес сам, чем перейдёт по ссылке в никуда."""
    return f"{public_url()}/activate?token={token}"


def verify_url(token: str) -> str:
    """Ссылка подтверждения адреса. Как и у активации: без ``PUBLIC_URL`` — путь."""
    return f"{public_url()}/verify-email?token={token}"


def unsubscribe_url(token: str) -> str:
    """Ссылка «не писать мне об этом обсуждении» (OPEN-DECISIONS §5).

    Ведёт на **страницу**, а не на изменяющий запрос: корпоративные почтовые фильтры
    ходят по ссылкам из писем заранее, и отписка по ``GET`` срабатывала бы у людей,
    которые её не нажимали, — молча и без их ведома.
    """
    return f"{public_url()}/comments/unsubscribe?token={token}"


def invite_letter(*, organization: str, inviter: str, token: str) -> Letter:
    return Letter(
        subject=f"Приглашение в организацию «{organization}» — Финанс-Элит",
        text=(f"{inviter} приглашает вас работать в организации «{organization}» "
              "на платформе «Финанс-Элит».\n\n"
              f"Чтобы войти, придумайте пароль по ссылке:\n{activation_url(token)}\n\n"
              "Ссылка действует неделю и срабатывает один раз.\n"
              "Если вы не ждали приглашения — просто не переходите по ней: "
              "без пароля учётная запись не работает." + _SIGNATURE),
    )


def access_link_letter(*, kind: str, organization: str, issued_by: str,
                       token: str) -> Letter:
    """Ссылка, выданная администратором: сброс забытого пароля или приглашение заново."""
    if kind == "reset":
        return Letter(
            subject="Ссылка для входа — Финанс-Элит",
            # Род того, кто выдал ссылку, неизвестен — о нём известен только адрес.
            # Поэтому «ссылка от …», а не «выдал(а) вам ссылку».
            text=(f"Вам выдана ссылка, чтобы задать новый пароль (от {issued_by}, "
                  f"организация «{organization}»):\n"
                  f"{activation_url(token)}\n\n"
                  "Прежний пароль перестанет действовать, а открытые входы закроются.\n"
                  "Ссылка действует неделю и срабатывает один раз. Если вы не просили "
                  "её — сообщите тому, кто управляет вашей организацией: пароль пока "
                  "не изменился." + _SIGNATURE),
        )
    return invite_letter(organization=organization, inviter=issued_by, token=token)


def reset_letter(*, token: str, has_password: bool) -> Letter:
    """Письмо по запросу «забыли пароль» — от самого человека, а не от администратора."""
    if not has_password:
        return Letter(
            subject="Вход в «Финанс-Элит»",
            text=("Вы просили доступ к учётной записи «Финанс-Элит». Пароль у неё ещё "
                  "не задан — придумайте его по ссылке:\n"
                  f"{activation_url(token)}\n\n"
                  "Ссылка действует неделю и срабатывает один раз." + _SIGNATURE),
        )
    return Letter(
        subject="Восстановление пароля — Финанс-Элит",
        text=("Вы просили восстановить пароль к «Финанс-Элит». Задайте новый по "
              f"ссылке:\n{activation_url(token)}\n\n"
              "Ссылка действует неделю и срабатывает один раз; открытые входы после "
              "смены пароля закроются. Если второй фактор включён, код из приложения "
              "спросят и здесь — письмо его не заменяет.\n\n"
              "Если это были не вы — ничего делать не нужно: пока по ссылке не перешли, "
              "пароль прежний." + _SIGNATURE),
    )


def new_device_letter(*, device: str, ip: str, when: str) -> Letter:
    """Вход с устройства, которого у этой учётной записи ещё не было (обещание C2).

    Устройство и адрес присылает сам браузер — это **подсказка, а не удостоверение**, и
    письмо говорит об этом теми же словами, что и список входов в профиле: узнаваемая
    строка иначе читается как доказательство, что вход был свой.
    """
    return Letter(
        subject="Вход в «Финанс-Элит» с нового устройства",
        text=("В вашу учётную запись вошли с устройства, которого раньше у неё не было."
              f"\n\nКогда: {when}\nУстройство: {device or 'не определилось'}\n"
              f"Адрес: {ip or 'неизвестен'}\n\n"
              "Устройство и адрес присылает сам браузер, подделать их несложно — это "
              "подсказка, а не доказательство.\n\n"
              "Если это были вы — ничего делать не нужно. Если нет — смените пароль и "
              "закройте лишние входы в профиле: смена пароля закрывает их все, кроме "
              "текущего." + _SIGNATURE),
        informational=True,
    )


def verify_email_letter(*, token: str) -> Letter:
    """Письмо «подтвердите адрес» — единственное, что уходит на неподтверждённый ящик.

    Иначе подтверждение недостижимо: чтобы получить письмо, нужно подтвердить адрес,
    а чтобы подтвердить — получить письмо.
    """
    return Letter(
        subject="Подтверждение адреса — Финанс-Элит",
        text=("Подтвердите, что этот адрес ваш, — перейдите по ссылке:\n"
              f"{verify_url(token)}\n\n"
              "До подтверждения платформа не будет присылать на него уведомления о "
              "входах и упоминаниях в обсуждениях: если адрес указан с опечаткой, они "
              "уходили бы постороннему. Ссылки для входа и восстановления пароля это "
              "не затрагивает — они приходят как обычно.\n\n"
              "Ссылка действует неделю. Если вы её не просили — просто не переходите."
              + _SIGNATURE),
    )


# --- Письма о деньгах (пакет G, G4) ---
#
# Все три — **дверные**: они о доступе к собственной организации, и запереть их за
# подтверждением адреса значило бы узнать о закрытии записи уже после. Каждое называет
# срок числом, что будет дальше, и оба выхода: оплату в продукте и оплату по счёту.

def billing_url() -> str:
    """Куда ведёт письмо о деньгах — сразу на вкладку оплаты. Пусто без ``PUBLIC_URL``:
    ссылка в никуда хуже, чем названный словами раздел."""
    base = public_url()
    return f"{base}/organization?tab=billing" if base else ""


def _pay_where(link: str) -> str:
    return (f"в разделе «Тариф и оплата»:\n{link}" if link
            else "в разделе «Тариф и оплата» (настройки организации)")


_BY_INVOICE = ("Оплачиваете по счёту? Напишите платформе — назначение тарифа она сделает "
               "сама, и отсчёт начнётся с оплаты.")


def rub(amount: int) -> str:
    """Сумма словами письма: «2 900 ₽». Разряды — пробелом, как пишут по-русски."""
    return f"{amount:,} ₽".replace(",", " ")


def period_ending_letter(*, organization: str, product: str, plan: str, ends: str,
                         days: int, grace_days: int, link: str, note: str = "") -> Letter:
    """За неделю до конца оплаченного периода.

    ``note`` — почему автопродление, на которое клиент рассчитывал, не сработает (G5):
    выключилось оно не его рукой, и узнать об этом он должен за неделю, а не по
    закрытой записи.
    """
    return Letter(
        subject=f"Оплаченный период «{product}» заканчивается — {organization}",
        text=(f"Оплаченный период тарифа «{plan}» ({product}) у организации "
              f"«{organization}» закончится {ends} — через {days} дн.\n\n"
              + (f"{note}\n\n" if note else "")
              + f"Чтобы работа не прерывалась, продлите оплату {_pay_where(link)}\n\n"
              f"Если не продлить, после окончания периода ещё {grace_days} дней всё "
              "работает как обычно. Затем изменение данных закроется до оплаты — "
              "просмотр, расчёт и выгрузка останутся: ваши числа остаются вашими.\n\n"
              + _BY_INVOICE + _SIGNATURE),
    )


# --- Автопродление (G5) ---
#
# Все дверные: они о деньгах, списанных (или не списанных) с карты клиента, и запереть
# их за подтверждением адреса значило бы списывать молча. Каждое называет сумму, способ
# и выход — выключить автопродление или оплатить вручную.

def renewal_notice_letter(*, organization: str, product: str, plan: str, amount: int,
                          months: int, method: str, ends: str, days: int,
                          link: str) -> Letter:
    """За неделю до списания: деньги клиента не списываются без письма **до** этого."""
    return Letter(
        subject=f"Автопродление «{product}»: скоро списание {rub(amount)} — {organization}",
        text=(f"У организации «{organization}» включено автопродление тарифа «{plan}» "
              f"({product}). Оплаченный период закончится {ends} — через {days} дн.\n\n"
              f"В течение суток до конца периода с «{method}» будет списано {rub(amount)} "
              f"за {months} мес., и период продолжится без перерыва.\n\n"
              f"Если продлевать не нужно, выключите автопродление {_pay_where(link)}\n"
              "Тогда ничего списано не будет, и период просто закончится." + _SIGNATURE),
    )


def renewal_charged_letter(*, organization: str, product: str, plan: str, amount: int,
                           months: int, method: str, paid_until: str, link: str) -> Letter:
    return Letter(
        subject=f"Автопродление «{product}»: списано {rub(amount)} — {organization}",
        text=(f"С «{method}» списано {rub(amount)} за {months} мес. тарифа «{plan}» "
              f"({product}) организации «{organization}». Оплачено до {paid_until}.\n\n"
              f"Выключить автопродление можно {_pay_where(link)}" + _SIGNATURE),
    )


def renewal_failed_letter(*, organization: str, product: str, plan: str, amount: int,
                          method: str, reason: str, next_try: str, attempts_left: int,
                          stopped: bool, ends: str, grace_days: int, link: str) -> Letter:
    """Списание не прошло: почему, что дальше и как оплатить самому.

    Три продолжения, и письмо называет своё: будет следующая попытка (с датой и числом
    оставшихся); попыток больше не будет; автопродление выключено совсем (способ больше
    не принимается или выросла цена) — тогда сказано, как включить его снова.
    """
    if stopped:
        then = ("Автопродление выключено, сохранённый способ оплаты забыт. Включить его "
                "снова можно оплатой с отметкой согласия.")
    elif attempts_left > 0:
        then = (f"Следующая попытка — {next_try}, осталось попыток: {attempts_left}. "
                "Если за это время оплатить вручную, повторного списания не будет.")
    else:
        then = "Попыток списания больше не будет."
    return Letter(
        subject=f"Автопродление «{product}» не прошло — {organization}",
        text=(f"Списание {rub(amount)} с «{method}» за тариф «{plan}» ({product}) "
              f"организации «{organization}» не состоялось: {reason}.\n\n{then}\n\n"
              f"Оплаченный период заканчивается {ends}; после него ещё {grace_days} дней "
              "всё работает как обычно, затем изменение данных закроется до оплаты — "
              "просмотр, расчёт и выгрузка останутся.\n\n"
              f"Оплатить вручную можно {_pay_where(link)}\n\n" + _BY_INVOICE + _SIGNATURE),
    )


def renewal_unknown_letter(*, organization: str, product: str, plan: str, amount: int,
                           method: str, link: str) -> Letter:
    """Провайдер не ответил: **неизвестно**, прошло ли списание — так и сказано.

    Назвать это отказом значило бы предложить оплатить второй раз, а успехом — продлить
    период за деньги, которых, может быть, не было.
    """
    return Letter(
        subject=f"Автопродление «{product}»: списание не подтверждено — {organization}",
        text=(f"Мы попытались списать {rub(amount)} с «{method}» за тариф «{plan}» "
              f"({product}) организации «{organization}», но платёжный провайдер не "
              "ответил, и неизвестно, прошло ли списание.\n\n"
              "Повторно не списываем, чтобы не взять деньги дважды. Если провайдер "
              "подтвердит платёж, период продлится сам. Если в выписке списания нет, "
              f"оплатите вручную {_pay_where(link)}" + _SIGNATURE),
    )


def period_ended_letter(*, organization: str, product: str, plan: str, ended: str,
                        grace_until: str, days_left: int, link: str) -> Letter:
    """Период кончился, идёт льготный срок: работа продолжается, но время названо."""
    return Letter(
        subject=f"Оплаченный период «{product}» закончился — {organization}",
        text=(f"Оплаченный период тарифа «{plan}» ({product}) у организации "
              f"«{organization}» закончился {ended}.\n\n"
              f"Работа продолжается как обычно ещё {days_left} дн. — до {grace_until}. "
              "Затем изменение данных закроется до оплаты; просмотр, расчёт и выгрузка "
              "останутся.\n\n"
              f"Продлить оплату можно {_pay_where(link)}\n\n" + _BY_INVOICE + _SIGNATURE),
    )


def access_restricted_letter(*, organization: str, product: str, plan: str,
                             link: str) -> Letter:
    """Льготный срок кончился: запись закрыта. Письмо говорит и что **осталось** —
    иначе «закрыто» читается как «данные забрали»."""
    return Letter(
        subject=f"Изменение данных в «{product}» закрыто до оплаты — {organization}",
        text=(f"Льготный срок после окончания оплаченного периода тарифа «{plan}» "
              f"({product}) закончился. Изменение данных у организации «{organization}» "
              "закрыто до оплаты.\n\n"
              "Просмотр, расчёт и выгрузка работают — ваши данные остаются вашими и "
              "доступны целиком.\n\n"
              f"Чтобы вернуть изменение данных, оплатите тариф {_pay_where(link)}\n\n"
              + _BY_INVOICE + _SIGNATURE),
    )
