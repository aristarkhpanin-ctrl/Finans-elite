"""Почта платформы: письма и способ их отправить (ADMIN-DECOMPOSITION.md, D1).

До этой фазы у продукта не было ни одного исходящего письма, и всё держалось на «ссылку
передайте лично». Это не мелочь: приглашённый не мог войти, пока пригласивший не дошёл до
него ногами, а забытый пароль владельца организации не восстанавливался **никак**.

**Пока почта не настроена, платформа не делает вид, что письма уходят.** Это правило
дома в его самом буквальном виде: строчка «приглашение отправлено», за которой ничего не
происходило, однажды уже стоила приглашённым нескольких дней ожидания письма, которого
не было. Поэтому:

* отправка выключена по умолчанию (``MAIL_BACKEND=off``) — включает её тот, кто задал
  адрес сервера и проверил, что письма доходят;
* :func:`mail_enabled` спрашивают **все**, кто собирается сказать человеку «письмо ушло»,
  — экран входа, приглашение участника, выдача ссылки;
* :func:`send` **не бросает исключений и не врёт**: неудача возвращается вызывающему
  словами, и он обязан её показать. Письмо, потерянное молча, хуже неотправленного.

**Ручная ссылка не исчезает.** Почта — добавление к «передайте лично», а не замена: при
неудачной отправке (а её причин не счесть — от опечатки в адресе до чужого спам-фильтра)
администратор по-прежнему видит ссылку и передаёт её сам.

**Ответы на письма никто не читает.** Ящика для входящей почты у платформы нет, и каждое
письмо говорит об этом прямо: тишина в ответ на «а что это было?» выглядит как
пренебрежение, а на деле письмо просто некуда прислать.
"""
from __future__ import annotations

import logging
import os
import smtplib
from dataclasses import dataclass
from email.headerregistry import Address
from email.message import EmailMessage

log = logging.getLogger("finans")

#: Как отправляем: ``off`` (по умолчанию — не отправляем вовсе), ``smtp`` (настоящий
#: сервер), ``memory`` (складываем в список — тесты и разработка).
_BACKENDS = ("off", "smtp", "memory")

def public_url() -> str:
    """Куда ведут ссылки в письмах. Письмо уходит наружу, и относительный путь в нём
    бесполезен: адрес приложения знает только тот, кто его развернул.

    Читается на каждом вызове, а не при импорте — как и всё остальное окружение здесь:
    модуль импортируется один раз за процесс, а переменные меняют и тесты, и
    эксплуатация.
    """
    return os.getenv("PUBLIC_URL", "").rstrip("/")


def backend() -> str:
    """Читается на каждом вызове, а не при импорте: окружение меняют и тесты, и
    эксплуатация, а модуль импортируется один раз за процесс."""
    value = os.getenv("MAIL_BACKEND", "off").strip().lower() or "off"
    return value if value in _BACKENDS else "off"


def mail_enabled() -> bool:
    """Отправляем ли мы письма вообще.

    Спрашивают все, кто собирается пообещать человеку письмо. Отдельного «мягкого»
    состояния («вроде настроена, но не уверены») нет намеренно: обещание либо есть, либо
    его не дают.
    """
    return backend() != "off"


def _timeout() -> float:
    """Секунды на разговор с сервером. Короткий: отправка стоит посреди чужого действия."""
    return float(os.getenv("SMTP_TIMEOUT", "10"))


def _smtp_settings() -> tuple[str, int, str, str, str]:
    host = os.getenv("SMTP_HOST", "").strip()
    if not host:
        # Fail-fast с названной причиной — как с ``JWT_SECRET``: «включил отправку, но
        # не сказал куда» это не рабочее состояние, а тихо не уходящие письма.
        raise RuntimeError("MAIL_BACKEND=smtp, но SMTP_HOST не задан: "
                           "укажите адрес почтового сервера или выключите отправку")
    mode = os.getenv("SMTP_TLS", "starttls").strip().lower()
    default_port = "465" if mode == "ssl" else "587"
    return (host, int(os.getenv("SMTP_PORT", default_port)),
            os.getenv("SMTP_USER", ""), os.getenv("SMTP_PASSWORD", ""), mode)


@dataclass(frozen=True)
class Letter:
    """Готовое письмо: тема и текст. Без HTML — намеренно.

    Письмо платформы состоит из одной ссылки и двух абзацев объяснения; вёрстка добавила
    бы к нему только повод для спам-фильтра и вторую версию текста, которая разойдётся с
    первой.
    """

    subject: str
    text: str


@dataclass(frozen=True)
class Sent:
    """Чем кончилась отправка. ``ok=False`` — вызывающий обязан сказать это человеку."""

    ok: bool
    #: Причина словами (пустая при успехе) — она уходит на экран, а не только в лог.
    error: str = ""
    #: Пытались ли вообще: ``False`` при выключенной почте. «Не отправляли» и
    #: «отправляли, не вышло» — разные ответы, и путать их нельзя.
    attempted: bool = True


#: Письма, отправленные бэкендом ``memory`` — для тестов и разработки.
_outbox: list[tuple[str, Letter]] = []


def outbox() -> list[tuple[str, Letter]]:
    """Что «ушло» в режиме ``memory``: пары (адрес, письмо)."""
    return list(_outbox)


def clear_outbox() -> None:
    _outbox.clear()


def send(to: str, letter: Letter) -> Sent:
    """Отправить письмо. **Не бросает исключений** — неудача возвращается словами.

    Отправка стоит посреди чужого действия: приглашения участника, входа, сброса пароля.
    Уронить это действие из-за недоступного почтового сервера значило бы поставить работу
    платформы в зависимость от чужой — тот же довод, что у проверки паролей по утечкам.
    Поэтому неудача не исключение, а **часть ответа**, и вызывающий обязан её показать.
    """
    kind = backend()
    if kind == "off":
        return Sent(ok=False, attempted=False,
                    error="почта не настроена: письма платформа не отправляет")
    if not to or "@" not in to:
        return Sent(ok=False, error=f"адрес «{to}» не похож на почтовый")
    if kind == "memory":
        _outbox.append((to, letter))
        return Sent(ok=True)
    try:
        _send_smtp(to, letter)
    except (OSError, smtplib.SMTPException) as exc:            # noqa: BLE001 — см. выше
        log.warning("письмо не отправлено на %s: %s", to, exc)
        return Sent(ok=False, error=f"почтовый сервер не принял письмо: {exc}")
    return Sent(ok=True)


def _send_smtp(to: str, letter: Letter) -> None:
    host, port, user, password, mode = _smtp_settings()
    message = EmailMessage()
    message["Subject"] = letter.subject
    local, _, domain = os.getenv("MAIL_FROM", "no-reply@finans-elite.ru").partition("@")
    message["From"] = Address(os.getenv("MAIL_FROM_NAME", "Финанс-Элит"), local, domain)
    message["To"] = to
    message.set_content(letter.text)
    if mode == "ssl":
        with smtplib.SMTP_SSL(host, port, timeout=_timeout()) as smtp:
            _deliver(smtp, user, password, message)
        return
    with smtplib.SMTP(host, port, timeout=_timeout()) as smtp:
        if mode == "starttls":
            smtp.starttls()
        _deliver(smtp, user, password, message)


def _deliver(smtp: smtplib.SMTP, user: str, password: str, message: EmailMessage) -> None:
    if user:
        smtp.login(user, password)
    smtp.send_message(message)


# --- Тексты писем ---
#
# Все письма устроены одинаково: что произошло, что сделать, что делать, если это были
# не вы, и подпись с оговоркой про ответы. Пароля и кода второго фактора в письмах нет
# **никогда** — только одноразовые ссылки, которые гаснут после использования.

_SIGNATURE = ("\n\n—\nЭто письмо отправила платформа «Финанс-Элит».\n"
              "Отвечать на него бесполезно: ящик входящие письма не принимает.")


def activation_url(token: str) -> str:
    """Ссылка активации для письма. Без ``PUBLIC_URL`` — путь: пусть лучше человек
    подставит адрес сам, чем перейдёт по ссылке в никуда."""
    return f"{public_url()}/activate?token={token}"


def invite_letter(*, organization: str, inviter: str, token: str) -> Letter:
    return Letter(
        subject=f"Приглашение в организацию «{organization}» — Финанс-Элит",
        text=(f"{inviter} приглашает вас работать в организации «{organization}» "
              "на платформе «Финанс-Элит».\n\n"
              f"Чтобы войти, придумайте пароль по ссылке:\n{activation_url(token)}\n\n"
              "Ссылка действует неделю и срабатывает один раз.\n"
              "Если вы не ждали приглашения — просто не переходите по ней: "
              "без пароля учётная запись не работает." + _SIGNATURE),
    )


def access_link_letter(*, kind: str, organization: str, issued_by: str,
                       token: str) -> Letter:
    """Ссылка, выданная администратором: сброс забытого пароля или приглашение заново."""
    if kind == "reset":
        return Letter(
            subject="Ссылка для входа — Финанс-Элит",
            text=(f"{issued_by} (организация «{organization}») выдал вам ссылку, чтобы "
                  "задать новый пароль:\n"
                  f"{activation_url(token)}\n\n"
                  "Прежний пароль перестанет действовать, а открытые входы закроются.\n"
                  "Ссылка действует неделю и срабатывает один раз. Если вы не просили "
                  "её — сообщите тому, кто управляет вашей организацией: пароль пока "
                  "не изменился." + _SIGNATURE),
        )
    return invite_letter(organization=organization, inviter=issued_by, token=token)


def reset_letter(*, token: str, has_password: bool) -> Letter:
    """Письмо по запросу «забыли пароль» — от самого человека, а не от администратора."""
    if not has_password:
        return Letter(
            subject="Вход в «Финанс-Элит»",
            text=("Вы просили доступ к учётной записи «Финанс-Элит». Пароль у неё ещё "
                  "не задан — придумайте его по ссылке:\n"
                  f"{activation_url(token)}\n\n"
                  "Ссылка действует неделю и срабатывает один раз." + _SIGNATURE),
        )
    return Letter(
        subject="Восстановление пароля — Финанс-Элит",
        text=("Вы просили восстановить пароль к «Финанс-Элит». Задайте новый по "
              f"ссылке:\n{activation_url(token)}\n\n"
              "Ссылка действует неделю и срабатывает один раз; открытые входы после "
              "смены пароля закроются. Если второй фактор включён, код из приложения "
              "спросят и здесь — письмо его не заменяет.\n\n"
              "Если это были не вы — ничего делать не нужно: пока по ссылке не перешли, "
              "пароль прежний." + _SIGNATURE),
    )


def new_device_letter(*, device: str, ip: str, when: str) -> Letter:
    """Вход с устройства, которого у этой учётной записи ещё не было (обещание C2).

    Устройство и адрес присылает сам браузер — это **подсказка, а не удостоверение**, и
    письмо говорит об этом теми же словами, что и список входов в профиле: узнаваемая
    строка иначе читается как доказательство, что вход был свой.
    """
    return Letter(
        subject="Вход в «Финанс-Элит» с нового устройства",
        text=("В вашу учётную запись вошли с устройства, которого раньше у неё не было."
              f"\n\nКогда: {when}\nУстройство: {device or 'не определилось'}\n"
              f"Адрес: {ip or 'неизвестен'}\n\n"
              "Устройство и адрес присылает сам браузер, подделать их несложно — это "
              "подсказка, а не доказательство.\n\n"
              "Если это были вы — ничего делать не нужно. Если нет — смените пароль и "
              "закройте лишние входы в профиле: смена пароля закрывает их все, кроме "
              "текущего." + _SIGNATURE),
    )
