"""Ключи доступа к API (ADMIN-DECOMPOSITION.md, D5): выпуск, разбор, отпечаток, права.

Чистые функции без базы и без FastAPI — их зовут CRUD и зависимости.

**Ключ писал только чтение — теперь может и записывать, но не «просто так»**
(OPEN-DECISIONS §3). Возражение было верным: у любой записи в журнале есть автор, а
«модель изменил ключ» — не автор. Снято оно не отменой возражения, а тем, что автор
нашёлся: **автор записи — человек, выпустивший ключ**, а сам ключ идёт пометкой в той же
записи (`audit_log.via_key`). Так устроена ответственность за доверенность: спросить можно
с выдавшего, отозвать можно доступ, и в журнале видно обоих. Второе возражение — «ключ
переживает увольнение» — снято тем же движением, каким смена пароля закрывает сеансы:
ключ работает, **пока работает его автор** (см. `deps.key_author`).

**Права выбираются при выпуске, по умолчанию — только чтение.** Ключ для BI остаётся
читающим, ключ для обмена с 1С получает ровно то, что ему нужно. «Ключ умеет всё» — не
вариант: он живёт в чужом сервере, и цена его утечки равна тому, что ему позволено.

**Секрет показывается один раз.** Хранится только отпечаток (SHA-256): украденная база
не даёт ключей, а «покажите ещё раз» невозможно ни для кого, включая платформу. Тот же
приём, что у резервных кодов второго фактора.

**Префикс не секрет.** Первые знаки ключа хранятся открыто: по ним ключ находят в базе
(без перебора всех отпечатков) и узнают в списке — «какой из трёх ключей отозвать» иначе
превращается в гадание.
"""
from __future__ import annotations

import hashlib
import secrets
from dataclasses import dataclass

from .rbac import Perm

#: Опознавательный признак: по нему запрос отличают от JWT ещё до похода в базу.
PREFIX = "fe"

#: Длина открытой части (её видно в списке) и секретной (её видят один раз).
PREFIX_LEN = 8
SECRET_LEN = 32

#: Сколько ключей держим на организацию. Не предел мощности, а гигиена: тридцать ключей
#: в списке означают, что никто уже не знает, какой из них где живёт.
MAX_KEYS_PER_ORG = 20

#: Что ключ умеет **всегда**: читать данные организации и запускать расчёт. Расчёт здесь
#: по тому же доводу, по какому он открыт неплательщику (B2) — это способ **посмотреть**
#: свои числа, а не изменить их.
#:
#: Читать ключ умеет всегда и тогда, когда ему разрешили писать: ключ, который может
#: создать проект, но не может его прочитать, — ловушка, а не ограничение.
READ_PERMS = frozenset({Perm.PROJECT_READ, Perm.PROJECT_CALCULATE})

#: Что можно **добавить** при выпуске. Ровно две вещи, и обе про обмен данными.
WRITE_PERMS = frozenset({Perm.PROJECT_CREATE, Perm.PROJECT_UPDATE})

#: Полный словарь прав ключа. Чего здесь нет — и почему:
#:
#: * **удаление** (`project.delete`) — единственное необратимое действие над моделью
#:   клиента, а ключ работает в чужом скрипте без человека рядом. Цикл с опечаткой
#:   сотрёт портфель молча, и восстановить его будет нечем;
#: * **реплика в обсуждении** (`comment.write`) — у реплики есть автор, который написал
#:   слова. «Ключ сказал» — не разговор, и приписать его выпустившему нельзя: он этих
#:   слов не писал (в отличие от правки модели, которую он поручил ключу сделать);
#: * **участники, тариф, организация** — дверь в саму организацию, а не в её данные.
ALLOWED_PERMS = READ_PERMS | WRITE_PERMS

#: Сколько запросов в минуту принимаем от одного ключа. Единственное новое число: цикл в
#: чужом скрипте не должен валить базу, а честной работе интегратора пяти запросов в
#: секунду хватает с запасом.
#:
#: Счёт идёт **в памяти процесса** (как и весь `ratelimit`): на нескольких рабочих
#: процессах предел умножается на их число. Это останавливает сорвавшийся цикл, а не
#: настойчивого злоумышленника, — и сказано здесь, а не обещано как защита.
MAX_REQUESTS_PER_MINUTE = 300


def effective_perms(scopes: list[str] | None) -> frozenset[Perm]:
    """Что ключу позволено на самом деле: выбранное при выпуске плюс чтение.

    **Пустой список — это чтение, а не «всё».** Так выглядят ключи, выпущенные до того,
    как права стали выбирать: молча дописать им запись значило бы расширить доступ,
    которого никто не просил, — ровно в тех ключах, что уже лежат в чужих серверах.

    Незнакомое право игнорируется, а не роняет запрос: ключ старше словаря прав обязан
    продолжать читать, а не перестать работать посреди ночной выгрузки.
    """
    chosen = {p for p in ALLOWED_PERMS if p.value in set(scopes or [])}
    return frozenset(READ_PERMS | chosen)


def unknown_scopes(scopes: list[str]) -> list[str]:
    """Права из запроса, которых ключу не бывает, — чтобы назвать их при отказе."""
    allowed = {p.value for p in ALLOWED_PERMS}
    return [s for s in scopes if s not in allowed]


@dataclass(frozen=True)
class NewKey:
    """Только что выпущенный ключ: показать один раз, сохранить отпечаток."""

    #: Полная строка вида ``fe_<префикс>_<секрет>`` — уходит человеку и больше нигде
    #: не появляется.
    token: str
    prefix: str
    fingerprint: str


def fingerprint(token: str) -> str:
    """Отпечаток ключа. SHA-256 без соли — намеренно.

    Медленный хэш нужен там, где секрет угадывают по словарю; здесь секрет — 32 знака
    случайности из ``secrets``, и подбирать его бессмысленно. Зато быстрый отпечаток
    проверяется на каждом запросе, не превращая ключ в тормоз.
    """
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def generate() -> NewKey:
    """Выпустить ключ: открытый префикс + секрет."""
    prefix = secrets.token_hex(PREFIX_LEN // 2)
    secret = secrets.token_urlsafe(SECRET_LEN)
    token = f"{PREFIX}_{prefix}_{secret}"
    return NewKey(token=token, prefix=prefix, fingerprint=fingerprint(token))


def looks_like_key(token: str) -> bool:
    """Похоже ли на ключ доступа. Нужна до разбора: JWT и ключ приходят одним заголовком,
    и перепутать их — значит ответить «недействительный токен» тому, у кого просто
    ключ вместо входа."""
    return token.startswith(f"{PREFIX}_")


def parse_prefix(token: str) -> str | None:
    """Открытая часть ключа — по ней его ищут в базе. ``None``, если это не ключ."""
    parts = token.split("_", 2)
    if len(parts) != 3 or parts[0] != PREFIX or not parts[1] or not parts[2]:
        return None
    return parts[1]


def masked(prefix: str) -> str:
    """Как ключ выглядит в списке: `fe_1a2b3c4d_…`. Полного секрета не знает никто."""
    return f"{PREFIX}_{prefix}_…"
