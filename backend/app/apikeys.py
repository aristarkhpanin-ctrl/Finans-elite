"""Ключи доступа к API (ADMIN-DECOMPOSITION.md, D5): выпуск, разбор, отпечаток.

Чистые функции без базы и без FastAPI — их зовут CRUD и зависимости.

**Ключ читает, но не пишет.** Это решение, а не недоделка. У любой записи в журнале есть
автор, и «модель изменил ключ» — не автор: спросить с него нельзя, отозвать задним числом
сделанное нельзя, а привязать ключ к человеку значит выдать его действия за его же —
хотя ключ живёт в чужом сервере и переживает увольнение. Спрос при этом на чтение:
выгрузить показатели в BI, забрать отчёт в 1С, свести портфель проектов. Запись —
отдельный разговор про атрибуцию и квоты, и он назван в плане, а не сделан молча.

**Секрет показывается один раз.** Хранится только отпечаток (SHA-256): украденная база
не даёт ключей, а «покажите ещё раз» невозможно ни для кого, включая платформу. Тот же
приём, что у резервных кодов второго фактора.

**Префикс не секрет.** Первые знаки ключа хранятся открыто: по ним ключ находят в базе
(без перебора всех отпечатков) и узнают в списке — «какой из трёх ключей отозвать» иначе
превращается в гадание.
"""
from __future__ import annotations

import hashlib
import secrets
from dataclasses import dataclass

#: Опознавательный признак: по нему запрос отличают от JWT ещё до похода в базу.
PREFIX = "fe"

#: Длина открытой части (её видно в списке) и секретной (её видят один раз).
PREFIX_LEN = 8
SECRET_LEN = 32

#: Сколько ключей держим на организацию. Не предел мощности, а гигиена: тридцать ключей
#: в списке означают, что никто уже не знает, какой из них где живёт.
MAX_KEYS_PER_ORG = 20


@dataclass(frozen=True)
class NewKey:
    """Только что выпущенный ключ: показать один раз, сохранить отпечаток."""

    #: Полная строка вида ``fe_<префикс>_<секрет>`` — уходит человеку и больше нигде
    #: не появляется.
    token: str
    prefix: str
    fingerprint: str


def fingerprint(token: str) -> str:
    """Отпечаток ключа. SHA-256 без соли — намеренно.

    Медленный хэш нужен там, где секрет угадывают по словарю; здесь секрет — 32 знака
    случайности из ``secrets``, и подбирать его бессмысленно. Зато быстрый отпечаток
    проверяется на каждом запросе, не превращая ключ в тормоз.
    """
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


def generate() -> NewKey:
    """Выпустить ключ: открытый префикс + секрет."""
    prefix = secrets.token_hex(PREFIX_LEN // 2)
    secret = secrets.token_urlsafe(SECRET_LEN)
    token = f"{PREFIX}_{prefix}_{secret}"
    return NewKey(token=token, prefix=prefix, fingerprint=fingerprint(token))


def looks_like_key(token: str) -> bool:
    """Похоже ли на ключ доступа. Нужна до разбора: JWT и ключ приходят одним заголовком,
    и перепутать их — значит ответить «недействительный токен» тому, у кого просто
    ключ вместо входа."""
    return token.startswith(f"{PREFIX}_")


def parse_prefix(token: str) -> str | None:
    """Открытая часть ключа — по ней его ищут в базе. ``None``, если это не ключ."""
    parts = token.split("_", 2)
    if len(parts) != 3 or parts[0] != PREFIX or not parts[1] or not parts[2]:
        return None
    return parts[1]


def masked(prefix: str) -> str:
    """Как ключ выглядит в списке: `fe_1a2b3c4d_…`. Полного секрета не знает никто."""
    return f"{PREFIX}_{prefix}_…"
