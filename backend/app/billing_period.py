"""Срок оплаченного периода и что происходит после него (OPEN-DECISIONS §1).

До этого модуля подписка **не кончалась**. Все три места, менявшие её, ставили
``status="active"``, а ``current_period_end`` не заполнял никто — оплаченный один раз
тариф действовал вечно. Хуже: из-за этого **весь механизм B2** («режим чтения и
выгрузки при неоплате») — написанный, оттестированный, умеющий объяснить клиенту
причину — не мог включиться ни по какому пути продукта. Сработать он мог только от
ручной приостановки оператором, а это другое поле и другой текст.

**Состояние выводится, а не хранится.** Здесь чистые функции над (`status`,
`current_period_end`, `now`); в базе лежит только дата конца периода — факт оплаты.
Хранить ещё и «просрочен ли он сейчас» значило бы завести вторую правду, которую надо
кем-то поддерживать: пока фоновая задача не добежала, доступ считался бы по вчерашнему
состоянию. У платформы фоновых задач нет вовсе, и заводить их ради того, что выводится
из даты, — самый дорогой способ получить расхождение.

Три решения, которые важнее кода:

* **Ноль срока — это «не истекает», а не «истёк давно».** У бесплатного и пробного
  тарифов периода нет: за них не платили, и отнимать у них нечего. У корпоративного
  (цена по запросу) — тоже: его условия согласуют вне продукта, и тридцать дней с
  момента, когда оператор его поставил, были бы выдуманным сроком.
* **Период ставит платёж, а не смена тарифа.** Назначение, за которое никто не платил,
  отсчёта не начинает.

  Здесь стояло уточнение «административная смена — это `POST …/billing/subscription`,
  право `billing.manage`». Про отсчёт оно было верным, а про право — нет: `billing.manage`
  есть у **владельца организации-клиента**, то есть «административной» та смена не была
  вовсе — клиент выдавал себе платный тариф сам, бесплатно и навсегда (срока при ней не
  ставилось). F1 закрыл дорогу: клиентским маршрутом ходят только вниз, платный тариф
  включает оплата, а назначить его вправе платформа — `POST /admin/organizations/{id}/
  subscription`, и там оплата по счёту **начинает** отсчёт наравне с провайдерами.
* **Платформа никогда не говорит «вы отменили подписку».** Неуплата даёт ``past_due`` —
  буквально то, что произошло. ``canceled`` — это акт, и приписывать его клиенту,
  который просто забыл карту, нельзя. Автоматически его не ставит никто.

И **льготный срок настоящий**: пока он идёт, организация работает как обычно, а клиент
предупреждён. Ограничение, наступающее в день окончания периода, — это не строгость, а
ловушка: человек узнаёт о проблеме в тот момент, когда уже не может её решить в продукте.
"""
from __future__ import annotations

from datetime import datetime, timedelta, timezone

from .plans import Plan

#: Длительность оплаченного периода. Прайс объявлен «в месяц», и тридцать дней — его
#: прямое прочтение. Календарный месяц (30/31/28) дал бы февральскому платежу другой
#: срок, чем январскому, при одной и той же цене.
PERIOD_DAYS = 30

#: Льготный срок после окончания периода: работа продолжается, клиент предупреждён.
#: Две недели — чтобы отпуск или забытая карта не отрезали работу, и чтобы «потом
#: разберусь» не растянулось на квартал.
GRACE_DAYS = 14

#: Статус, в который переводит неуплата. Один: см. третье решение в шапке модуля.
OVERDUE_STATUS = "past_due"


def paid_period_end(plan: Plan, paid_at: datetime, months: int = 1) -> datetime | None:
    """Конец оплаченного периода, либо ``None`` — если тариф не истекает.

    ``None`` возвращается для бесплатных и «по запросу» тарифов и означает именно
    «срока нет», а не «срок в прошлом»: читатель этого поля обязан различать.

    ``months`` — сколько периодов оплачено сразу. Умолчание ``1`` оставляет прежнее
    поведение обоих провайдеров байт-в-байт; больше одного бывает при оплате по счёту,
    которую проводит оператор платформы (F1). Ноль и отрицательное срока не дают:
    «оплачено ноль месяцев» — это не оплата, и притворяться ею нельзя.
    """
    if plan.price_on_request or plan.price_rub <= 0 or months <= 0:
        return None
    return paid_at + timedelta(days=PERIOD_DAYS * months)


def _aware(value: datetime) -> datetime:
    """Привести к UTC-aware. SQLite возвращает наивные datetime, PostgreSQL — с зоной;
    сравнение тех и других роняет расчёт на одной базе и молча проходит на другой."""
    return value if value.tzinfo is not None else value.replace(tzinfo=timezone.utc)


def days_overdue(period_end: datetime | None, now: datetime) -> int:
    """Сколько полных суток прошло с конца периода. ``0`` — период не кончился или его нет."""
    if period_end is None:
        return 0
    delta = _aware(now) - _aware(period_end)
    return max(0, delta.days)


def in_grace(period_end: datetime | None, now: datetime) -> bool:
    """Идёт ли льготный срок: период кончился, но работа ещё не ограничена."""
    overdue = days_overdue(period_end, now)
    return 0 < overdue <= GRACE_DAYS


def grace_days_left(period_end: datetime | None, now: datetime) -> int:
    """Сколько суток льготного срока осталось (≥ 0). Для предупреждения клиенту.

    Число, а не «скоро»: «осталось 3 дня» человек кладёт в календарь, «скоро» — нет.
    """
    return max(0, GRACE_DAYS - days_overdue(period_end, now))


def effective_status(status: str, period_end: datetime | None,
                     now: datetime | None = None) -> str:
    """Действующий статус подписки: хранимый плюс то, что сделало с ним время.

    Возвращает хранимый статус, пока период не кончился или пока идёт льготный срок, и
    :data:`OVERDUE_STATUS` после него. Уже неоплаченный статус (поставленный человеком)
    временем не «чинится»: истёкшая дата не может сделать подписку действующей.
    """
    if status in {"past_due", "canceled"}:
        return status
    if period_end is None:
        return status
    return OVERDUE_STATUS if days_overdue(period_end, now or datetime.now(timezone.utc)) \
        > GRACE_DAYS else status


#: За сколько суток до конца периода напомнить (G4). Неделя — чтобы успеть оплатить по
#: счёту (бухгалтерия клиента платит не в тот же день) и чтобы письмо не забылось раньше,
#: чем понадобится.
REMINDER_DAYS = 7


def reminder_stage(status: str, period_end: datetime | None,
                   now: datetime) -> str | None:
    """О чём пора написать владельцу подписки: ``ending`` · ``ended`` · ``overdue``.

    ``None`` — писать не о чем: периода нет вовсе («не истекает» — не «истёк давно»), до
    конца больше :data:`REMINDER_DAYS` суток, или подписка ``canceled`` — это акт
    человека, автоматически его не ставит никто, и о нём уже знают.

    Этап выводится из тех же функций, что и доступ: письмо не может сказать «запись
    закрыта», пока экран ещё пускает, и наоборот.
    """
    if period_end is None or status == "canceled":
        return None
    if effective_status(status, period_end, now) == OVERDUE_STATUS:
        return "overdue"
    end, current = _aware(period_end), _aware(now)
    if current >= end:
        return "ended"
    if end - current <= timedelta(days=REMINDER_DAYS):
        return "ending"
    return None
