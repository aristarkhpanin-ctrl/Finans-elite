"""Сумма прописью — для счёта и акта (пакет G, G6).

Первичный документ называет сумму дважды — цифрами и словами, и слова обязаны быть
правильными: «двадцать один рублей» в акте выглядит так же небрежно, как опечатка в
цифрах, и бухгалтерия клиента вернёт такой документ.

Правила, которые здесь держатся и проверяются тестом на каждую форму:

* согласование по числу: 1 рубль · 2–4 рубля · 5–20 рублей, **11–14 — всегда «рублей»**
  (одиннадцать, а не «один»), дальше по последней цифре (21 рубль, 22 рубля);
* **тысяча — женского рода**: одна тысяча, две тысячи; миллион и миллиард — мужского;
* ноль называется словом («ноль рублей»), копейки — цифрами («00 копеек»), как принято
  в платёжных документах.
"""
from __future__ import annotations

__all__ = ["number_in_words", "plural", "rubles_in_words"]

_UNITS_M = ["", "один", "два", "три", "четыре", "пять", "шесть", "семь", "восемь",
            "девять"]
_UNITS_F = ["", "одна", "две", "три", "четыре", "пять", "шесть", "семь", "восемь",
            "девять"]
_TEENS = ["десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
          "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"]
_TENS = ["", "", "двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят",
         "семьдесят", "восемьдесят", "девяносто"]
_HUNDREDS = ["", "сто", "двести", "триста", "четыреста", "пятьсот", "шестьсот",
             "семьсот", "восемьсот", "девятьсот"]

#: Разряды: величина, формы слова и род (тысяча — женского).
_SCALES: list[tuple[int, tuple[str, str, str], bool]] = [
    (10 ** 9, ("миллиард", "миллиарда", "миллиардов"), False),
    (10 ** 6, ("миллион", "миллиона", "миллионов"), False),
    (10 ** 3, ("тысяча", "тысячи", "тысяч"), True),
]

#: Предел: суммы платформы — тарифы, а не бюджеты; больше — почти наверняка ошибка.
LIMIT = 10 ** 12


def plural(n: int, one: str, few: str, many: str) -> str:
    """Форма слова для числа: 1 — ``one``, 2–4 — ``few``, прочее — ``many``;
    11–14 — всегда ``many``."""
    n = abs(n) % 100
    if 11 <= n <= 14:
        return many
    n %= 10
    if n == 1:
        return one
    if 2 <= n <= 4:
        return few
    return many


def _triad(n: int, feminine: bool) -> list[str]:
    words = [_HUNDREDS[n // 100]]
    rest = n % 100
    if 10 <= rest <= 19:
        words.append(_TEENS[rest - 10])
    else:
        words.append(_TENS[rest // 10])
        words.append((_UNITS_F if feminine else _UNITS_M)[rest % 10])
    return [w for w in words if w]


def number_in_words(n: int, feminine: bool = False) -> str:
    """Целое число словами: ``31320`` → «тридцать одна тысяча триста двадцать»."""
    if n < 0 or n >= LIMIT:
        raise ValueError(f"сумма вне пределов прописи: {n}")
    if n == 0:
        return "ноль"
    words: list[str] = []
    for size, forms, fem in _SCALES:
        chunk = n // size % 1000
        if chunk:
            words += _triad(chunk, fem) + [plural(chunk, *forms)]
    words += _triad(n % 1000, feminine)
    return " ".join(words)


def rubles_in_words(rubles: int, kopecks: int = 0) -> str:
    """«Тридцать одна тысяча триста двадцать рублей 00 копеек» — с заглавной буквы."""
    if not 0 <= kopecks <= 99:
        raise ValueError(f"копеек не бывает {kopecks}")
    text = (f"{number_in_words(rubles)} {plural(rubles, 'рубль', 'рубля', 'рублей')} "
            f"{kopecks:02d} {plural(kopecks, 'копейка', 'копейки', 'копеек')}")
    return text[0].upper() + text[1:]
