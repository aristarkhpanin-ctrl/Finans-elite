"""Режим доступа организации: полная работа или чтение и выгрузка (B2).

Статус подписки писался с самого начала и **не читался никем**: неплательщик работал
ровно как плательщик. Здесь он начинает действовать — и действует по правилу 7 плана:
**неоплата не конфискует данные**. Организация в ограниченном режиме видит свои модели,
считает их и выгружает документы; заводить новые и править старые — нельзя.

Что именно закрывается, решается **одним множеством прав** (:data:`WRITE_PERMS`), а не
списком маршрутов: список маршрутов пришлось бы дополнять при каждом новом эндпоинте, и
однажды его забыли бы дополнить.

Три решения, которые здесь важнее кода:

* **Расчёт остаётся открытым.** План называл его среди закрываемого, но расчёт — это
  способ посмотреть свои числа: экран результатов зовёт его при каждом открытии, и
  DOCX собирается тем же движком. Закрыв расчёт, мы закрыли бы просмотр и выгрузку,
  обещанные в том же предложении.
* **Оплата остаётся открытой.** Иначе ограничение за неоплату — ловушка: клиент не может
  ни работать, ни заплатить. По той же причине открыто управление участниками: отозвать
  доступ у уволенного нужно и неплательщику, а особенно ему.
* **Ограничение — на продукт, а не на организацию.** Подписка своя у каждого продукта;
  просроченный «Аудит» не имеет отношения к оплаченному «Элит». Ручная приостановка —
  наоборот, про организацию целиком: это решение о клиенте, а не о покупке.
"""
from __future__ import annotations

from dataclasses import dataclass

from sqlalchemy.orm import Session

from . import crud
from .plans import PRODUCT_NAME
from .rbac import Perm

#: Права, закрытые в режиме чтения и выгрузки: всё, что **меняет** содержимое.
#: Чтение, расчёт, участники, тариф и оплата остаются доступными.
WRITE_PERMS = frozenset({Perm.PROJECT_CREATE, Perm.PROJECT_UPDATE, Perm.PROJECT_DELETE,
                         # Реплика обсуждения (D3) — тоже содержимое организации: она
                         # хранится, цитируется в документах и переживает автора.
                         Perm.COMMENT_WRITE})

#: Статусы подписки, переводящие продукт в режим чтения и выгрузки.
UNPAID_STATUSES = frozenset({"past_due", "canceled"})


@dataclass(frozen=True)
class Restriction:
    """Почему организация ограничена и что с этим делать.

    ``kind`` различает два случая, потому что различается **выход** из них: неоплата
    снимается оплатой, ручная приостановка — только тем, кто её поставил. Показать
    неплательщику «обратитесь в поддержку», а приостановленному «оплатите тариф» значило
    бы отправить обоих не туда.
    """

    kind: str          # "suspended" | "unpaid"
    reason: str        # что произошло
    remedy: str        # что делать

    @property
    def detail(self) -> str:
        return f"{self.reason} {self.remedy}"


def restriction_for(db: Session, org_id: str, product: str = "business") -> Restriction | None:
    """Ограничение организации по продукту; ``None`` — обычная работа.

    Ручная приостановка проверяется первой: пока она стоит, оплата ничего не меняет, и
    обещать обратное («оплатите — и заработает») нельзя.
    """
    org = crud.get_organization(db, org_id)
    if org is not None and org.suspended_at is not None:
        reason = org.suspended_by and f"Приостановлена оператором платформы ({org.suspended_by})." \
            or "Организация приостановлена оператором платформы."
        if org.suspend_reason:
            reason = f"{reason.rstrip('.')}: {org.suspend_reason}."
        return Restriction(
            kind="suspended",
            reason=reason,
            remedy="Данные доступны для просмотра и выгрузки. Снять приостановку может "
                   "только платформа — напишите в поддержку.",
        )

    sub = crud.get_subscription(db, org_id, product)
    if sub is not None and sub.status in UNPAID_STATUSES:
        name = PRODUCT_NAME.get(product, product)
        what = "отменена" if sub.status == "canceled" else "не оплачена"
        return Restriction(
            kind="unpaid",
            reason=f"Подписка на «{name}» {what}.",
            remedy="Данные доступны для просмотра и выгрузки; чтобы снова заводить и "
                   "править их, оплатите тариф.",
        )
    return None
