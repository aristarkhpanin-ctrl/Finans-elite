"""Что показать человеку о его входе: устройство и адрес (C1).

Чистые функции над строкой браузера и заголовками запроса — без базы и без FastAPI,
поэтому проверяются обычными тестами.

**Обе величины приходят снаружи и обе можно подделать.** Строку ``User-Agent`` пишет сам
браузер; адрес за обратным прокси берётся из заголовка, который прокси обязан
перезаписывать, — если он этого не делает, клиент может прислать любой. Поэтому здесь
они **подсказка для владельца учётной записи** («это точно был я?»), а не удостоверение
устройства и не основание для решений: ни один отказ платформы на них не опирается.
"""
from __future__ import annotations

#: Грубая карта «подстрока → название». Порядок важен: у Edge в строке есть и «Chrome»,
#: у Chrome — и «Safari», поэтому частное идёт раньше общего. Точного разбора не делаем:
#: библиотека распознавания устарела бы молча, а неверная подпись хуже общей.
_BROWSERS = (
    ("YaBrowser", "Яндекс.Браузер"),
    ("Edg/", "Edge"),
    ("OPR/", "Opera"),
    ("Firefox", "Firefox"),
    ("Chrome", "Chrome"),
    ("Safari", "Safari"),
)

_SYSTEMS = (
    ("Android", "Android"),
    ("iPhone", "iPhone"),
    ("iPad", "iPad"),
    ("Windows", "Windows"),
    ("Macintosh", "macOS"),
    ("Mac OS X", "macOS"),
    ("Linux", "Linux"),
)


def device_label(user_agent: str | None) -> str:
    """«Chrome · Windows» из строки браузера. Не распозналось — так и сказано.

    Пустая строка превратилась бы в пустую ячейку, и человек читал бы её как «данных
    нет»; «неизвестное устройство» честнее: данные есть, но они ничего не говорят.
    """
    raw = (user_agent or "").strip()
    if not raw:
        return "Устройство неизвестно"
    browser = next((name for key, name in _BROWSERS if key in raw), "")
    system = next((name for key, name in _SYSTEMS if key in raw), "")
    if browser and system:
        return f"{browser} · {system}"
    return browser or system or "Неизвестный браузер"


def client_ip(*, forwarded_for: str | None, remote: str | None) -> str:
    """Адрес клиента: первый в ``X-Forwarded-For``, иначе адрес соединения.

    Первый, а не последний: цепочку слева направо дописывают прокси, и левее всех стоит
    тот, кто обратился первым. За правильно настроенным обратным прокси это и есть
    клиент; за неправильно настроенным — то, что клиент захотел написать, и полагаться
    на это в проверках нельзя (см. модуль).
    """
    chain = (forwarded_for or "").split(",")
    first = chain[0].strip()
    return (first or (remote or "").strip())[:45]
