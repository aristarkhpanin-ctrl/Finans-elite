"""Отправка письма в стороне от запроса, с записью исхода в журнал (D1).

Два письма платформы нельзя отправлять прямо в ответе:

* **«забыли пароль»** — ответ обязан быть одинаковым для существующего и
  несуществующего адреса, иначе форма превращается в проверялку «есть ли у вас такой
  клиент». Одинаковый текст этого не даёт: разговор с почтовым сервером занимает
  секунды, и **время ответа** выдаёт существование адреса не хуже текста;
* **уведомление о новом входе** — ронять вход из-за недоступного почтового сервера
  нельзя, а ждать его молча значит заставить человека смотреть на крутящийся индикатор.

Исход при этом не теряется: он пишется в журналы организаций человека теми же словами,
какими вернулся из отправки. «Письмо не ушло» в журнале — это то, с чем администратор
придёт разбираться; молчание — это то, о чём никто не узнает.

Сессия берётся **новая и на том же движке**, что у запроса: фоновая задача выполняется
после ответа, когда сессия запроса уже закрыта. Именно на том же — глобальная фабрика
сессий в тестах указывает на другую базу, и запись уходила бы мимо той, которую тест
потом читает.
"""
from __future__ import annotations

from sqlalchemy.engine import Engine
from sqlalchemy.orm import Session

from . import crud, mail
from .mail import Letter


def send_and_log(bind: Engine, user_id: str, to: str, letter: Letter,
                 action: str) -> None:
    """Отправить письмо и записать исход в журнал. Исключений не бросает."""
    result = mail.send(to, letter)
    detail = ("письмо отправлено" if result.ok
              else f"письмо не ушло: {result.error}")
    with Session(bind=bind) as db:
        user = crud.get_user(db, user_id)
        if user is not None:
            crud.log_user_action(db, user, action, details=detail)
