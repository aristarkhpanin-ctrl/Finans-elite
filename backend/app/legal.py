"""Публичные документы: оферта, политика обработки ПД, согласие на обработку ПД и
реквизиты (пакет L, L5).

Без них сайт не проходит проверку платёжного агрегатора, а политика обработки
персональных данных обязательна по ч. 2 ст. 18.1 152-ФЗ — тем более что платформа
собирает события пользования. Правила, и каждое держит тест:

* **текст — черновик, пока владелец не утвердил редакцию.** Тексты подготовила
  платформа, юрист их не читал; до ``LEGAL_DOCS_EDITION`` над каждым стоит «Черновик», а
  «Готовность» называет это проблемой. Выдать черновик за проверенный документ — хуже,
  чем не опубликовать его вовсе;
* **реквизиты подставляются из ``SELLER_*``** — тех же, что у счетов и актов (G6); второй
  копии реквизитов нет. Незаданное **видно** пометкой «[не указано: …]» и перечнем
  ``missing``, а не пустым местом, которое читается как опечатка;
* **политика описывает то, что код делает на самом деле**: категории данных — перечень
  :data:`PD_CATEGORIES`, и рядом с каждой — цель, основание и срок; утверждение «страницы
  не загружают ресурсы со сторонних серверов» стережёт фронтовый тест;
* **согласие — отдельный документ и отдельная отметка** (ч. 1 ст. 9 152-ФЗ в ред. с
  1.09.2025): в учётной записи сохраняются время и редакция.
"""
