def seller_problems(values: dict[str, str] | None = None) -> list[str]:
    """Чего не хватает для публичных документов — словами (для «Готовности»)."""
    values = values if values is not None else seller_values()
    problems = [f"не задано {SELLER_ENV[key][0]} — {SELLER_ENV[key][1]}"
                for key in REQUIRED if not values.get(key)]
    if values.get("inn") and not valid_inn(values["inn"]):
        problems.append(f"SELLER_INN «{values['inn']}» не проходит проверку контрольной цифры")
    if values.get("ogrn") and not valid_ogrn(values["ogrn"]):
        problems.append(f"SELLER_OGRN «{values['ogrn']}» не проходит проверку контрольной "
                        "цифры")
    if not values.get("site"):
        problems.append("не задан PUBLIC_URL — документы не называют адрес сайта")
    return problems


class _Fill(dict):
    """Подстановка реквизитов: незаданное становится видимой пометкой и попадает в
    перечень ``missing`` — пустое место в договоре читалось бы как опечатка."""

    def __init__(self, values: dict[str, str]):
        super().__init__(values)
        self.missing: list[str] = []

    def __missing__(self, key: str) -> str:
        return self._mark(key)

    def __getitem__(self, key: str) -> str:
        value = super().get(key, "")
        return value if value else self._mark(key)

    def _mark(self, key: str) -> str:
        label = phrase(LABELS.get(key, key))
        if label not in self.missing:
            self.missing.append(label)
        return f"[не указано: {label}]"


def phrase(label: str) -> str:
    """Подпись посреди фразы: «Адрес» → «адрес», а «ИНН» остаётся «ИНН» — аббревиатура
    строчными («инн», «огрн») читается как опечатка."""
    if len(label) > 1 and label[1].isupper():
        return label
    return label[:1].lower() + label[1:]


