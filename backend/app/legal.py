#: Редакция, когда владелец её не утвердил. Пишется и в учётную запись: человек
#: соглашался с черновиком — так и записано.
DRAFT = "черновик"
DRAFT_NOTE = ("Черновик: текст подготовлен платформой и юристом не проверен. Пока владелец "
              "сервиса не утвердит редакцию, считать его окончательным нельзя.")
EDITION_MAX = 64

#: Отказ регистрации без согласия — словами, а не «поле обязательно».
CONSENT_REQUIRED = ("Без согласия на обработку персональных данных зарегистрироваться "
                    "нельзя: адрес почты и имя нужны, чтобы завести учётную запись и "
                    "входить в неё. Текст согласия — по ссылке рядом с отметкой.")


def edition() -> str:
    """Утверждённая редакция документов или «черновик»."""
    raw = env("LEGAL_DOCS_EDITION")
    return raw[:EDITION_MAX] if raw else DRAFT


def is_draft() -> bool:
    return edition() == DRAFT


def record_consent(user, *, terms: bool) -> None:
    """Записать согласие на обработку ПД (и принятие оферты) — время и редакцию."""
    now = datetime.now(timezone.utc)
    current = edition()
    user.pd_consent_at = now
    user.pd_consent_edition = current
    if terms:
        user.terms_accepted_at = now
        user.terms_edition = current


