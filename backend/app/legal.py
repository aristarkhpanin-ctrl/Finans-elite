REQUISITES = LegalDoc(
    "requisites", "Реквизиты",
    "Кто оказывает услугу и как с ним связаться.",
    (Section("Исполнитель", ()),),   # заполняется из PUBLIC_FIELDS
)

DOCS: dict[str, LegalDoc] = {d.slug: d for d in (OFFER, PRIVACY, CONSENT, REQUISITES)}


@dataclass
class Rendered:
    slug: str
    title: str
    summary: str
    edition: str
    draft: bool
    sections: list[Section]
    #: Чего не хватает в тексте — подписями для человека.
    missing: list[str] = field(default_factory=list)


def _pd_paragraphs() -> tuple[str, ...]:
    return tuple(f"{c.what}: {c.data}. Зачем: {c.purpose}. Основание: {c.basis}. "
                 f"Срок: {c.kept}." for c in PD_CATEGORIES)


def _requisites_paragraphs(values: _Fill) -> tuple[str, ...]:
    shown = []
    for key in PUBLIC_FIELDS + ("site",):
        if key == "kpp" and len(values.get("inn", "")) == 12:
            continue     # у ИП КПП не бывает — пометка «не указано» была бы ложной
        shown.append(f"{LABELS[key]}: {values[key]}")
    return tuple(shown)


def render(slug: str) -> Rendered | None:
    """Документ с подставленными реквизитами; ``None`` — такого документа нет."""
    doc = DOCS.get(slug)
    if doc is None:
        return None
    values = _Fill(seller_values())
    sections = []
    for section in doc.sections:
        paragraphs = section.paragraphs
        if doc is PRIVACY and section.heading.startswith("2."):
            paragraphs = _pd_paragraphs()
        if doc is REQUISITES:
            paragraphs = _requisites_paragraphs(values)
        sections.append(Section(section.heading,
                                tuple(p.format_map(values) for p in paragraphs)))
    current = edition()
    return Rendered(slug=doc.slug, title=doc.title, summary=doc.summary, edition=current,
                    draft=current == DRAFT, sections=sections, missing=values.missing)
