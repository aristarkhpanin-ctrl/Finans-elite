"""Зачёт НДС (SPEC §11).

Метод «по отгрузке»: исходящий НДС (с продаж) признаётся при отгрузке, а с полученного
аванса — при получении денег (наиболее ранняя из дат, :func:`output_on_earliest_date`);
входной — при закупке/приобретении. Сальдо — **по налоговому периоду**: НДС к уплате за
период = исходящий − входной за период − перенесённый излишек прошлых периодов, не ниже
нуля. Излишек вычетов на конец периода возмещается (п. 1 ст. 176 НК РФ: деньги — через
срок проверки) либо переносится в зачёт будущих периодов (:func:`settle_vat`).

Кэш-фло отражается **с НДС**; ОПУ — **без НДС**. НДС к уплате и возмещение попадают в
строку «Налоги» (C12); перенесённый излишек и ожидаемое возмещение — в B7.
"""
from __future__ import annotations

from dataclasses import dataclass
from decimal import Decimal

from ..money import ZERO
from ..series import zeros


def output_on_earliest_date(accrued: list[Decimal],
                            advances: list[Decimal]) -> list[Decimal]:
    """Исходящий НДС «по отгрузке» на **наиболее раннюю** из дат (п. 1 ст. 167 НК РФ).

    С полученного аванса НДС начисляется в месяце получения денег, а при отгрузке
    принимается к вычету (п. 8 ст. 171, п. 6 ст. 172). Признание месяца — начисленное по
    отгрузке плюс прирост остатка НДС с авансов на конец месяца; уплаченный НДС с аванса
    лежит в B7 до отгрузки.

    ``advances`` — остаток НДС с авансов по сбыту, собранный **по строкам** тем же
    ``sales_timing``, что ведёт авансы B24. Не «максимум накопленного по отгрузке и по
    оплате»: при смешанных условиях (часть предоплатой, часть с отсрочкой) дебиторка строки
    погасила бы её же аванс, и НДС с аванса снова не начислялся бы. Без авансов признание
    совпадает с начислением.
    """
    out = zeros(len(accrued))
    prev = ZERO
    for t, (vat, adv) in enumerate(zip(accrued, advances, strict=True)):
        out[t] = vat + adv - prev
        prev = adv
    return out


#: Налоговый период НДС — квартал (ст. 163 НК РФ): по его итогам заявляется возмещение.
_QUARTER = 3


@dataclass
class VatSettlement:
    """Итог зачёта НДС по месяцам."""

    #: Прирост НДС к уплате за период нарастающим итогом периода: внутри периода бывает
    #: < 0 (излишек третьего месяца гасит налог первого), сумма за период ≥ 0. Уплата —
    #: по сроку периода (``_payment_schedule``), отсрочка — в B21.
    to_budget: list[Decimal]
    #: Излишек вычетов на конец месяца, ещё не заявленный к возмещению (B7): внутри
    #: периода — в любом режиме, между периодами — только при переносе в зачёт.
    credit: list[Decimal]
    #: Заявлено к возмещению и ещё не получено на конец месяца (B7).
    receivable: list[Decimal]
    #: Возмещение, полученное деньгами в месяце (уменьшает C12).
    refund: list[Decimal]


def settle_vat(vat_out: list[Decimal], vat_in: list[Decimal], n: int, *,
               period_months: int = 1, offset: int = 0,
               refund_lag: int | None = None) -> VatSettlement:
    """Сальдо НДС по налоговому периоду; излишек — к возмещению или в зачёт вперёд.

    ``period_months`` — длина периода сальдо (1, 3 или 12 мес. — периодичность уплаты
    модели), ``offset`` — смещение календарного года (:func:`~calc_core.reports.statements.
    tax_year_offset`): период кончается в календарном месяце, как и срок уплаты.
    ``refund_lag`` — через сколько месяцев после конца квартала приходит возмещение (п. 1
    ст. 176 НК РФ); ``None`` — излишек переносится в зачёт будущих периодов, как было до
    0.9.55.

    **Сальдо — за период, а не помесячно** (ст. 163, 173): помесячный зачёт при
    квартальной уплате платил налог за первый месяц квартала и копил излишек третьего,
    а при возмещении вернул бы через полгода налог, которого по декларации не было.
    Внутри периода ``to_budget`` — прирост нарастающей позиции периода, поэтому
    помесячный ряд проходит по уплате и балансу так же, как прежде; при помесячном
    периоде результат совпадает с прежним помесячным зачётом.

    **Возмещение заявляется по итогам квартала** — налогового периода НДС (ст. 163) — при
    любой периодичности уплаты не короче его. «Ежемесячно» — упрощение уплаты, а не
    период декларации: излишек месяца, как и прежде, гасит налог следующих месяцев
    квартала, и к возмещению уходит только то, что осталось на его конец. Иначе модель
    платила бы налог февраля и ждала возврата январского излишка до мая. «Ежегодно» —
    заявление по итогам года (тоже упрощение).
    """
    out = VatSettlement(to_budget=zeros(n), credit=zeros(n), receivable=zeros(n),
                        refund=zeros(n))
    claim_months = max(period_months, _QUARTER)   # кратно периоду сальдо: 3, 3 или 12
    carry = ZERO          # излишек прошлых периодов, перенесённый в зачёт
    net = ZERO            # исходящий − входной с начала периода
    payable_prev = ZERO   # НДС к уплате за период на конец прошлого месяца
    claimed = ZERO        # заявлено к возмещению и ещё не получено
    for t in range(n):
        net += vat_out[t] - vat_in[t]
        position = net - carry
        payable = max(ZERO, position)
        excess = max(ZERO, -position)
        out.to_budget[t] = payable - payable_prev
        payable_prev = payable
        if (t + offset) % period_months == period_months - 1:   # конец периода сальдо
            quarter_end = (t + offset) % claim_months == claim_months - 1
            if refund_lag is not None and quarter_end and excess > ZERO:
                claimed += excess
                if t + refund_lag < n:
                    out.refund[t + refund_lag] += excess
                carry = ZERO
                excess = ZERO
            else:
                carry = excess
            net = ZERO
            payable_prev = ZERO
        claimed -= out.refund[t]
        out.credit[t] = excess
        out.receivable[t] = claimed
    return out
